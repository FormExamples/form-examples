CREATE TABLE IF NOT EXISTS "echocardiogram_test_requests" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "status" varchar NOT NULL DEFAULT 'draft',
    "site_name" varchar NOT NULL DEFAULT '',
    "setting" varchar NOT NULL DEFAULT '',
    "referral_date" date NULL,
    "requested_by_date" date NULL,
    "echo_type" varchar NOT NULL DEFAULT '',
    "primary_indication" varchar NOT NULL DEFAULT '',
    "clinical_question" varchar NOT NULL DEFAULT '',
    "relevant_history" varchar NOT NULL DEFAULT '',
    "breathlessness" boolean NOT NULL DEFAULT false,
    "chest_pain" boolean NOT NULL DEFAULT false,
    "palpitations" boolean NOT NULL DEFAULT false,
    "syncope" boolean NOT NULL DEFAULT false,
    "oedema" boolean NOT NULL DEFAULT false,
    "nyha_class" varchar NOT NULL DEFAULT '',
    "ecg_findings" varchar NOT NULL DEFAULT '',
    "bnp_or_nt_probnp" double precision NULL,
    "known_murmur" boolean NOT NULL DEFAULT false,
    "previous_echo" varchar NOT NULL DEFAULT '',
    "previous_echo_date" date NULL,
    "ejection_fraction_known" double precision NULL,
    "on_cardiotoxic_chemotherapy" boolean NOT NULL DEFAULT false,
    "relevant_medications" varchar NOT NULL DEFAULT '',
    "urgency" varchar NOT NULL DEFAULT 'routine',
    "supervising_consultant" varchar NOT NULL DEFAULT '',
    "requester_contact" varchar NOT NULL DEFAULT '',
    "notes" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-echocardiogram_test_requests-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-echocardiogram_test_requests-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE
);


    "cht_result" varchar NOT NULL DEFAULT '',
    "pku_result" varchar NOT NULL DEFAULT '',
    "mcadd_result" varchar NOT NULL DEFAULT '',
    "msud_result" varchar NOT NULL DEFAULT '',
    "iva_result" varchar NOT NULL DEFAULT '',
    "ga1_result" varchar NOT NULL DEFAULT '',
    "hcu_result" varchar NOT NULL DEFAULT '',
    "clinical_context" text NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NULL,

    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "sample_taker_role" varchar NOT NULL DEFAULT '',
    "care_setting" varchar NOT NULL DEFAULT '',
    "record_date" date NULL,
    "time_of_birth" varchar NULL,

CREATE TABLE IF NOT EXISTS "sleep_study_test_results" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "originating_request_reference" varchar NOT NULL DEFAULT '',
    "report_status" varchar NOT NULL DEFAULT '',
    "performed_date" date NULL,
    "reported_date" date NULL,
    "study_type" varchar NOT NULL DEFAULT '',
    "study_adequacy" varchar NOT NULL DEFAULT '',
    "clinical_history" varchar NOT NULL DEFAULT '',
    "comparison_with_previous" varchar NOT NULL DEFAULT '',
    "total_recording_time_hours" double precision NULL,
    "total_sleep_time_hours" double precision NULL,
    "apnoea_hypopnoea_index" double precision NULL,
    "oxygen_desaturation_index" double precision NULL,
    "minimum_spo2_percent" double precision NULL,
    "time_below_90_percent_spo2" double precision NULL,
    "mean_heart_rate_bpm" integer NULL,
    "osa_severity" varchar NOT NULL DEFAULT '',
    "obstructive_sleep_apnoea" boolean NOT NULL DEFAULT false,
    "central_sleep_apnoea" boolean NOT NULL DEFAULT false,
    "periodic_limb_movements" boolean NOT NULL DEFAULT false,
    "nocturnal_hypoventilation" boolean NOT NULL DEFAULT false,
    "significant_desaturation" boolean NOT NULL DEFAULT false,
    "normal_study" boolean NOT NULL DEFAULT false,
    "findings_narrative" varchar NOT NULL DEFAULT '',
    "impression" varchar NOT NULL DEFAULT '',
    "reporting_category" varchar NOT NULL DEFAULT '',
    "recommended_follow_up" varchar NOT NULL DEFAULT '',
    "critical_result_communicated" boolean NOT NULL DEFAULT false,
    "reported_to" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-sleep_study_test_results-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-sleep_study_test_results-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE
);

ALTER TABLE sleep_study_test_results ALTER COLUMN id SET DEFAULT gen_random_uuid();

CREATE TABLE IF NOT EXISTS "glasgow_coma_scales" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "assessor_name" varchar NOT NULL DEFAULT '',
    "assessor_role" varchar NOT NULL DEFAULT '',
    "assessed_at" timestamp with time zone NULL,
    "setting" varchar NOT NULL DEFAULT '',
    "reason" text NOT NULL DEFAULT '',
    "intubated" varchar NOT NULL DEFAULT '',
    "sedated" varchar NOT NULL DEFAULT '',
    "paralysed" varchar NOT NULL DEFAULT '',
    "eye_response" varchar NOT NULL DEFAULT '',
    "eye_not_testable_reason" text NOT NULL DEFAULT '',
    "verbal_response" varchar NOT NULL DEFAULT '',
    "verbal_not_testable_reason" text NOT NULL DEFAULT '',
    "motor_response" varchar NOT NULL DEFAULT '',
    "motor_not_testable_reason" text NOT NULL DEFAULT '',
    "left_pupil_reactivity" varchar NOT NULL DEFAULT '',
    "right_pupil_reactivity" varchar NOT NULL DEFAULT '',
    "left_pupil_size_mm" double precision NULL,
    "right_pupil_size_mm" double precision NULL,
    "previous_total" integer NULL,
    "previous_motor_score" integer NULL,
    "previous_assessed_at" timestamp with time zone NULL,
    "clinical_note" text NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NULL,
    CONSTRAINT "fk-glasgow_coma_scales-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-glasgow_coma_scales-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE SET NULL ON UPDATE NO ACTION
);


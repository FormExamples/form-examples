CREATE TABLE IF NOT EXISTS "toxicology_test_results" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "originating_request_reference" varchar NOT NULL DEFAULT '',
    "report_status" varchar NOT NULL DEFAULT '',
    "performed_date" date NULL,
    "reported_date" date NULL,
    "specimen_condition" varchar NOT NULL DEFAULT '',
    "clinical_history" varchar NOT NULL DEFAULT '',
    "suspected_agent" varchar NOT NULL DEFAULT '',
    "time_since_ingestion_hours" double precision NULL,
    "paracetamol_level_mg_l" double precision NULL,
    "salicylate_level_mg_l" double precision NULL,
    "ethanol_level" double precision NULL,
    "lithium_level_mmol_l" double precision NULL,
    "digoxin_level" double precision NULL,
    "carboxyhaemoglobin_percent" double precision NULL,
    "drugs_of_abuse_screen" varchar NOT NULL DEFAULT '',
    "specific_drug_level" varchar NOT NULL DEFAULT '',
    "paracetamol_nomogram" varchar NOT NULL DEFAULT '',
    "overall_result_status" varchar NOT NULL DEFAULT '',
    "toxic_level_present" boolean NOT NULL DEFAULT false,
    "findings_narrative" varchar NOT NULL DEFAULT '',
    "impression" varchar NOT NULL DEFAULT '',
    "reporting_category" varchar NOT NULL DEFAULT '',
    "recommended_follow_up" varchar NOT NULL DEFAULT '',
    "critical_result_communicated" boolean NOT NULL DEFAULT false,
    "reported_to" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-toxicology_test_results-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-toxicology_test_results-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE
);

ALTER TABLE toxicology_test_results ALTER COLUMN id SET DEFAULT gen_random_uuid();

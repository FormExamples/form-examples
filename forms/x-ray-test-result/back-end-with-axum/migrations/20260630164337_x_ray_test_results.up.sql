CREATE TABLE IF NOT EXISTS "x_ray_test_results" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "originating_request_reference" varchar NOT NULL DEFAULT '',
    "report_status" varchar NOT NULL DEFAULT '',
    "performed_date" date NULL,
    "reported_date" date NULL,
    "body_region" varchar NOT NULL DEFAULT '',
    "laterality" varchar NOT NULL DEFAULT '',
    "projections" varchar NOT NULL DEFAULT '',
    "examination_adequacy" varchar NOT NULL DEFAULT '',
    "clinical_history" varchar NOT NULL DEFAULT '',
    "comparison_with_previous" varchar NOT NULL DEFAULT '',
    "findings_narrative" varchar NOT NULL DEFAULT '',
    "fracture" boolean NOT NULL DEFAULT false,
    "dislocation" boolean NOT NULL DEFAULT false,
    "consolidation" boolean NOT NULL DEFAULT false,
    "pneumothorax" boolean NOT NULL DEFAULT false,
    "pleural_effusion" boolean NOT NULL DEFAULT false,
    "foreign_body" boolean NOT NULL DEFAULT false,
    "free_air" boolean NOT NULL DEFAULT false,
    "bony_lesion" boolean NOT NULL DEFAULT false,
    "incidental_finding" boolean NOT NULL DEFAULT false,
    "impression" varchar NOT NULL DEFAULT '',
    "reporting_category" varchar NOT NULL DEFAULT '',
    "recommended_follow_up" varchar NOT NULL DEFAULT '',
    "critical_result_communicated" boolean NOT NULL DEFAULT false,
    "reported_to" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-x_ray_test_results-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-x_ray_test_results-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE
);

ALTER TABLE x_ray_test_results ALTER COLUMN id SET DEFAULT gen_random_uuid();

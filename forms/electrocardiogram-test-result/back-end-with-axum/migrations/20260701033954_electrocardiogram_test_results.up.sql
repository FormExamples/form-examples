CREATE TABLE IF NOT EXISTS "electrocardiogram_test_results" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "originating_request_reference" varchar NOT NULL DEFAULT '',
    "report_status" varchar NOT NULL DEFAULT '',
    "ecg_type" varchar NOT NULL DEFAULT '',
    "performed_date" date NULL,
    "reported_date" date NULL,
    "recording_quality" varchar NOT NULL DEFAULT '',
    "clinical_history" varchar NOT NULL DEFAULT '',
    "ventricular_rate_bpm" integer NULL,
    "rhythm" varchar NOT NULL DEFAULT '',
    "pr_interval_ms" integer NULL,
    "qrs_duration_ms" integer NULL,
    "qt_interval_ms" integer NULL,
    "qtc_ms" integer NULL,
    "cardiac_axis" varchar NOT NULL DEFAULT '',
    "st_elevation" boolean NOT NULL DEFAULT false,
    "st_depression" boolean NOT NULL DEFAULT false,
    "t_wave_inversion" boolean NOT NULL DEFAULT false,
    "pathological_q_waves" boolean NOT NULL DEFAULT false,
    "left_ventricular_hypertrophy" boolean NOT NULL DEFAULT false,
    "bundle_branch_block" boolean NOT NULL DEFAULT false,
    "ischaemia" boolean NOT NULL DEFAULT false,
    "normal_ecg" boolean NOT NULL DEFAULT false,
    "interpretation" varchar NOT NULL DEFAULT '',
    "comparison_with_previous" varchar NOT NULL DEFAULT '',
    "impression" varchar NOT NULL DEFAULT '',
    "reporting_category" varchar NOT NULL DEFAULT '',
    "recommended_follow_up" varchar NOT NULL DEFAULT '',
    "critical_result_communicated" boolean NOT NULL DEFAULT false,
    "reported_to" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-electrocardiogram_test_results-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-electrocardiogram_test_results-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE
);


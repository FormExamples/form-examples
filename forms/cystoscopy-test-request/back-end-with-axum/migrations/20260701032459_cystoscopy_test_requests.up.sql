CREATE TABLE IF NOT EXISTS "cystoscopy_test_requests" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "status" varchar NOT NULL DEFAULT 'draft',
    "site_name" varchar NOT NULL DEFAULT '',
    "setting" varchar NOT NULL DEFAULT '',
    "referral_date" date NULL,
    "requested_by_date" date NULL,
    "procedure" varchar NOT NULL DEFAULT '',
    "primary_indication" varchar NOT NULL DEFAULT '',
    "clinical_question" varchar NOT NULL DEFAULT '',
    "relevant_history" varchar NOT NULL DEFAULT '',
    "symptom_haematuria" boolean NOT NULL DEFAULT false,
    "symptom_dysuria" boolean NOT NULL DEFAULT false,
    "symptom_frequency" boolean NOT NULL DEFAULT false,
    "symptom_retention" boolean NOT NULL DEFAULT false,
    "visible_haematuria" boolean NOT NULL DEFAULT false,
    "current_uti" boolean NOT NULL DEFAULT false,
    "taking_anticoagulant" boolean NOT NULL DEFAULT false,
    "anticoagulant_agent" varchar NOT NULL DEFAULT '',
    "taking_antiplatelet" boolean NOT NULL DEFAULT false,
    "previous_bladder_cancer" boolean NOT NULL DEFAULT false,
    "urgency" varchar NOT NULL DEFAULT 'routine',
    "supervising_consultant" varchar NOT NULL DEFAULT '',
    "requester_contact" varchar NOT NULL DEFAULT '',
    "notes" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-cystoscopy_test_requests-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-cystoscopy_test_requests-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE
);

ALTER TABLE cystoscopy_test_requests ALTER COLUMN id SET DEFAULT gen_random_uuid();

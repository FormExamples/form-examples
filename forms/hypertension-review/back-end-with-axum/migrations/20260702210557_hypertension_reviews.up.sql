CREATE TABLE IF NOT EXISTS "hypertension_reviews" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "clinician_role" varchar NOT NULL DEFAULT '',
    "reviewed_at" date NULL,
    "practice_site" varchar NOT NULL DEFAULT '',
    "patient_identifier" varchar NOT NULL DEFAULT '',
    "age_band" varchar NOT NULL DEFAULT '',
    "sex" varchar NOT NULL DEFAULT '',
    "ethnicity" varchar NOT NULL DEFAULT '',
    "diagnosis_date" date NULL,
    "type2_diabetes" varchar NOT NULL DEFAULT '',
    "chronic_kidney_disease" varchar NOT NULL DEFAULT '',
    "established_cvd" varchar NOT NULL DEFAULT '',
    "atrial_fibrillation" varchar NOT NULL DEFAULT '',
    "clinic_systolic" integer NULL,
    "clinic_diastolic" integer NULL,
    "home_systolic" integer NULL,
    "home_diastolic" integer NULL,
    "monitoring_method" varchar NOT NULL DEFAULT '',
    "postural_drop" varchar NOT NULL DEFAULT '',
    "antihypertensive_agents" integer NULL,
    "adherence" varchar NOT NULL DEFAULT '',
    "side_effects" varchar NOT NULL DEFAULT '',
    "qrisk_percent" double precision NULL,
    "smoking_status" varchar NOT NULL DEFAULT '',
    "statin_therapy" varchar NOT NULL DEFAULT '',
    "bmi" double precision NULL,
    "lifestyle_advice" text NOT NULL DEFAULT '',
    "serum_creatinine" double precision NULL,
    "egfr" double precision NULL,
    "serum_potassium" double precision NULL,
    "hba1c" double precision NULL,
    "total_cholesterol" double precision NULL,
    "hdl_cholesterol" double precision NULL,
    "urine_acr" double precision NULL,
    "complications" text NOT NULL DEFAULT '',
    "review_context" text NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NULL,
    CONSTRAINT "fk-hypertension_reviews-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-hypertension_reviews-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE SET NULL ON UPDATE NO ACTION

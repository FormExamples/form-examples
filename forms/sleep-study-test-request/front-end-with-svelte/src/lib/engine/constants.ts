// Shared clinical thresholds for the Sleep Study Test Request engine.

/** Epworth above this threshold indicates abnormal daytime sleepiness (>10). */
export const EPWORTH_ABNORMAL = 11;

/** Epworth at or above this threshold indicates severe excessive sleepiness. */
export const EPWORTH_SEVERE = 16;

/** STOP-BANG at or above this threshold indicates high OSA risk. */
export const STOP_BANG_HIGH_RISK = 5;

/** STOP-BANG at or above this threshold indicates intermediate OSA risk. */
export const STOP_BANG_INTERMEDIATE = 3;

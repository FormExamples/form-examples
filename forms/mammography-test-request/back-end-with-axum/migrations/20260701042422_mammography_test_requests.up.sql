CREATE TABLE IF NOT EXISTS "mammography_test_requests" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "status" varchar NOT NULL DEFAULT 'draft',
    "site_name" varchar NOT NULL DEFAULT '',
    "setting" varchar NOT NULL DEFAULT '',
    "referral_date" date NULL,
    "requested_by_date" date NULL,
    "exam_type" varchar NOT NULL DEFAULT '',
    "primary_indication" varchar NOT NULL DEFAULT '',
    "clinical_question" varchar NOT NULL DEFAULT '',
    "relevant_history" varchar NOT NULL DEFAULT '',
    "laterality" varchar NOT NULL DEFAULT '',
    "symptom_lump" boolean NOT NULL DEFAULT false,
    "symptom_pain" boolean NOT NULL DEFAULT false,
    "symptom_nipple_discharge" boolean NOT NULL DEFAULT false,
    "symptom_skin_change" boolean NOT NULL DEFAULT false,
    "symptom_nipple_inversion" boolean NOT NULL DEFAULT false,
    "previous_mammogram" varchar NOT NULL DEFAULT '',
    "previous_mammogram_date" date NULL,
    "family_history_breast_cancer" boolean NOT NULL DEFAULT false,
    "breast_implants" boolean NOT NULL DEFAULT false,
    "pregnancy_or_lactating" varchar NOT NULL DEFAULT '',
    "hormone_replacement_therapy" boolean NOT NULL DEFAULT false,
    "urgency" varchar NOT NULL DEFAULT 'routine',
    "supervising_consultant" varchar NOT NULL DEFAULT '',
    "requester_contact" varchar NOT NULL DEFAULT '',
    "notes" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-mammography_test_requests-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-mammography_test_requests-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE
);

ALTER TABLE mammography_test_requests ALTER COLUMN id SET DEFAULT gen_random_uuid();

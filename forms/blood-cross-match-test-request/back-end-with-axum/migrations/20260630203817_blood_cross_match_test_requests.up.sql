CREATE TABLE IF NOT EXISTS "blood_cross_match_test_requests" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "status" varchar NOT NULL DEFAULT 'draft',
    "site_name" varchar NOT NULL DEFAULT '',
    "setting" varchar NOT NULL DEFAULT '',
    "referral_date" date NULL,
    "requested_by_date" date NULL,
    "request_type" varchar NOT NULL DEFAULT '',
    "component" varchar NOT NULL DEFAULT '',
    "units_required" integer NULL,
    "primary_indication" varchar NOT NULL DEFAULT '',
    "clinical_details" varchar NOT NULL DEFAULT '',
    "patient_blood_group" varchar NOT NULL DEFAULT '',
    "known_antibodies" boolean NOT NULL DEFAULT false,
    "antibody_detail" varchar NOT NULL DEFAULT '',
    "previous_transfusion" boolean NOT NULL DEFAULT false,
    "previous_transfusion_reaction" boolean NOT NULL DEFAULT false,
    "pregnant" boolean NOT NULL DEFAULT false,
    "sample_collected" varchar NOT NULL DEFAULT '',
    "collection_datetime" timestamp with time zone NULL,
    "two_sample_rule_met" boolean NOT NULL DEFAULT false,
    "required_by_datetime" timestamp with time zone NULL,
    "urgency" varchar NOT NULL DEFAULT 'routine',
    "supervising_consultant" varchar NOT NULL DEFAULT '',
    "requester_contact" varchar NOT NULL DEFAULT '',
    "notes" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-blood_cross_match_test_requests-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-blood_cross_match_test_requests-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE
);

ALTER TABLE blood_cross_match_test_requests ALTER COLUMN id SET DEFAULT gen_random_uuid();

CREATE TABLE IF NOT EXISTS "tumor_marker_test_requests" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "status" varchar NOT NULL DEFAULT 'draft',
    "site_name" varchar NOT NULL DEFAULT '',
    "setting" varchar NOT NULL DEFAULT '',
    "referral_date" date NULL,
    "requested_by_date" date NULL,
    "psa" boolean NOT NULL DEFAULT false,
    "ca125" boolean NOT NULL DEFAULT false,
    "ca19_9" boolean NOT NULL DEFAULT false,
    "carcinoembryonic_antigen_cea" boolean NOT NULL DEFAULT false,
    "alpha_fetoprotein_afp" boolean NOT NULL DEFAULT false,
    "beta_hcg" boolean NOT NULL DEFAULT false,
    "ca15_3" boolean NOT NULL DEFAULT false,
    "lactate_dehydrogenase_ldh" boolean NOT NULL DEFAULT false,
    "calcitonin" boolean NOT NULL DEFAULT false,
    "chromogranin_a" boolean NOT NULL DEFAULT false,
    "primary_indication" varchar NOT NULL DEFAULT '',
    "clinical_details" varchar NOT NULL DEFAULT '',
    "known_cancer_site" varchar NOT NULL DEFAULT '',
    "on_treatment" boolean NOT NULL DEFAULT false,
    "previous_marker_value" double precision NULL,
    "previous_marker_date" date NULL,
    "urgency" varchar NOT NULL DEFAULT 'routine',
    "supervising_consultant" varchar NOT NULL DEFAULT '',
    "requester_contact" varchar NOT NULL DEFAULT '',
    "notes" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-tumor_marker_test_requests-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-tumor_marker_test_requests-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE

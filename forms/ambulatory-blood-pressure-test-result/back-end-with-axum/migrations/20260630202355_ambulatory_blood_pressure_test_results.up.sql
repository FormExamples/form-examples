CREATE TABLE IF NOT EXISTS "ambulatory_blood_pressure_test_results" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "originating_request_reference" varchar NOT NULL DEFAULT '',
    "monitoring_type" varchar NOT NULL DEFAULT '',
    "report_status" varchar NOT NULL DEFAULT '',
    "performed_date" date NULL,
    "reported_date" date NULL,
    "valid_readings_percent" double precision NULL,
    "recording_adequate" boolean NOT NULL DEFAULT false,
    "clinical_history" varchar NOT NULL DEFAULT '',
    "daytime_average_systolic" double precision NULL,
    "daytime_average_diastolic" double precision NULL,
    "nighttime_average_systolic" double precision NULL,
    "nighttime_average_diastolic" double precision NULL,
    "twenty_four_hour_average_systolic" double precision NULL,
    "twenty_four_hour_average_diastolic" double precision NULL,
    "nocturnal_dip_percent" double precision NULL,
    "dipper_status" varchar NOT NULL DEFAULT '',
    "hypertension_confirmed" boolean NOT NULL DEFAULT false,
    "white_coat_effect" boolean NOT NULL DEFAULT false,
    "masked_hypertension" boolean NOT NULL DEFAULT false,
    "severe_hypertension" boolean NOT NULL DEFAULT false,
    "nocturnal_hypertension" boolean NOT NULL DEFAULT false,
    "normal_study" boolean NOT NULL DEFAULT false,
    "findings_narrative" varchar NOT NULL DEFAULT '',
    "comparison_with_previous" varchar NOT NULL DEFAULT '',
    "impression" varchar NOT NULL DEFAULT '',
    "reporting_category" varchar NOT NULL DEFAULT '',
    "recommended_follow_up" varchar NOT NULL DEFAULT '',
    "critical_result_communicated" boolean NOT NULL DEFAULT false,
    "reported_to" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-ambulatory_blood_pressure_test_results-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-ambulatory_blood_pressure_test_results-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE

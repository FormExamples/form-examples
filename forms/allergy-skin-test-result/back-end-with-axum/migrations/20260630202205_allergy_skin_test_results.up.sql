CREATE TABLE IF NOT EXISTS "allergy_skin_test_results" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "originating_request_reference" varchar NOT NULL DEFAULT '',
    "test_type" varchar NOT NULL DEFAULT '',
    "report_status" varchar NOT NULL DEFAULT '',
    "performed_date" date NULL,
    "reported_date" date NULL,
    "clinical_history" varchar NOT NULL DEFAULT '',
    "antihistamines_withheld" boolean NOT NULL DEFAULT false,
    "positive_control_valid" boolean NOT NULL DEFAULT false,
    "allergens_tested" varchar NOT NULL DEFAULT '',
    "wheal_sizes" varchar NOT NULL DEFAULT '',
    "specific_ige_results" varchar NOT NULL DEFAULT '',
    "sensitised_allergens" varchar NOT NULL DEFAULT '',
    "positive_reactions" boolean NOT NULL DEFAULT false,
    "sensitisation_confirmed" boolean NOT NULL DEFAULT false,
    "anaphylaxis_during_test" boolean NOT NULL DEFAULT false,
    "all_negative" boolean NOT NULL DEFAULT false,
    "test_invalid" boolean NOT NULL DEFAULT false,
    "interpretation" varchar NOT NULL DEFAULT '',
    "impression" varchar NOT NULL DEFAULT '',
    "reporting_category" varchar NOT NULL DEFAULT '',
    "recommended_follow_up" varchar NOT NULL DEFAULT '',
    "critical_result_communicated" boolean NOT NULL DEFAULT false,
    "reported_to" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-allergy_skin_test_results-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-allergy_skin_test_results-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE
);


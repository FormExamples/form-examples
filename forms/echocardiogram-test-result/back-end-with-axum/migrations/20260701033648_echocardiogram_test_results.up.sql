CREATE TABLE IF NOT EXISTS "echocardiogram_test_results" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "originating_request_reference" varchar NOT NULL DEFAULT '',
    "echo_type" varchar NOT NULL DEFAULT '',
    "performed_date" date NULL,
    "reported_date" date NULL,
    "report_status" varchar NOT NULL DEFAULT '',
    "study_quality" varchar NOT NULL DEFAULT '',
    "clinical_history" varchar NOT NULL DEFAULT '',
    "lv_ejection_fraction_percent" double precision NULL,
    "lv_function" varchar NOT NULL DEFAULT '',
    "lv_internal_diameter_diastole_mm" double precision NULL,
    "aortic_stenosis" varchar NOT NULL DEFAULT '',
    "aortic_regurgitation" varchar NOT NULL DEFAULT '',
    "mitral_stenosis" varchar NOT NULL DEFAULT '',
    "mitral_regurgitation" varchar NOT NULL DEFAULT '',
    "pulmonary_artery_systolic_pressure_mmhg" double precision NULL,
    "lv_hypertrophy" boolean NOT NULL DEFAULT false,
    "regional_wall_motion_abnormality" boolean NOT NULL DEFAULT false,
    "pericardial_effusion" boolean NOT NULL DEFAULT false,
    "vegetation" boolean NOT NULL DEFAULT false,
    "intracardiac_thrombus" boolean NOT NULL DEFAULT false,
    "normal_study" boolean NOT NULL DEFAULT false,
    "findings_narrative" varchar NOT NULL DEFAULT '',
    "comparison_with_previous" varchar NOT NULL DEFAULT '',
    "impression" varchar NOT NULL DEFAULT '',
    "reporting_category" varchar NOT NULL DEFAULT '',
    "recommended_follow_up" varchar NOT NULL DEFAULT '',
    "critical_result_communicated" boolean NOT NULL DEFAULT false,
    "reported_to" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-echocardiogram_test_results-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-echocardiogram_test_results-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE

CREATE TABLE IF NOT EXISTS "bronchoscopy_test_requests" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "status" varchar NOT NULL DEFAULT 'draft',
    "site_name" varchar NOT NULL DEFAULT '',
    "setting" varchar NOT NULL DEFAULT '',
    "referral_date" date NULL,
    "requested_by_date" date NULL,
    "procedure" varchar NOT NULL DEFAULT '',
    "primary_indication" varchar NOT NULL DEFAULT '',
    "clinical_question" varchar NOT NULL DEFAULT '',
    "relevant_history" varchar NOT NULL DEFAULT '',
    "symptom_haemoptysis" boolean NOT NULL DEFAULT false,
    "symptom_cough" boolean NOT NULL DEFAULT false,
    "symptom_breathlessness" boolean NOT NULL DEFAULT false,
    "symptom_weight_loss" boolean NOT NULL DEFAULT false,
    "imaging_findings" varchar NOT NULL DEFAULT '',
    "taking_anticoagulant" boolean NOT NULL DEFAULT false,
    "anticoagulant_agent" varchar NOT NULL DEFAULT '',
    "taking_antiplatelet" boolean NOT NULL DEFAULT false,
    "antiplatelet_agent" varchar NOT NULL DEFAULT '',
    "platelet_count" double precision NULL,
    "oxygen_dependent" boolean NOT NULL DEFAULT false,
    "asa_grade" varchar NOT NULL DEFAULT '',
    "sedation" varchar NOT NULL DEFAULT '',
    "urgency" varchar NOT NULL DEFAULT 'routine',
    "supervising_consultant" varchar NOT NULL DEFAULT '',
    "requester_contact" varchar NOT NULL DEFAULT '',
    "notes" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-bronchoscopy_test_requests-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-bronchoscopy_test_requests-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE
);


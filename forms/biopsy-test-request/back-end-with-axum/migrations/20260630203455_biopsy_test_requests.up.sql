CREATE TABLE IF NOT EXISTS "biopsy_test_requests" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "status" varchar NOT NULL DEFAULT 'draft',
    "site_name" varchar NOT NULL DEFAULT '',
    "setting" varchar NOT NULL DEFAULT '',
    "referral_date" date NULL,
    "requested_by_date" date NULL,
    "biopsy_site" varchar NOT NULL DEFAULT '',
    "biopsy_method" varchar NOT NULL DEFAULT '',
    "laterality" varchar NOT NULL DEFAULT '',
    "primary_indication" varchar NOT NULL DEFAULT '',
    "clinical_question" varchar NOT NULL DEFAULT '',
    "relevant_history" varchar NOT NULL DEFAULT '',
    "lesion_description" varchar NOT NULL DEFAULT '',
    "imaging_guidance_required" boolean NOT NULL DEFAULT false,
    "taking_anticoagulant" boolean NOT NULL DEFAULT false,
    "anticoagulant_agent" varchar NOT NULL DEFAULT '',
    "taking_antiplatelet" boolean NOT NULL DEFAULT false,
    "antiplatelet_agent" varchar NOT NULL DEFAULT '',
    "inr" double precision NULL,
    "platelet_count" double precision NULL,
    "bleeding_disorder" boolean NOT NULL DEFAULT false,
    "immunosuppressed" boolean NOT NULL DEFAULT false,
    "urgency" varchar NOT NULL DEFAULT 'routine',
    "supervising_consultant" varchar NOT NULL DEFAULT '',
    "requester_contact" varchar NOT NULL DEFAULT '',
    "notes" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-biopsy_test_requests-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-biopsy_test_requests-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE
);

ALTER TABLE biopsy_test_requests ALTER COLUMN id SET DEFAULT gen_random_uuid();

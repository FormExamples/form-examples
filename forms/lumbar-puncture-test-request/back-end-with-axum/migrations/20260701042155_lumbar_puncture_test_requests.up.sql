CREATE TABLE IF NOT EXISTS "lumbar_puncture_test_requests" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "status" varchar NOT NULL DEFAULT 'draft',
    "site_name" varchar NOT NULL DEFAULT '',
    "setting" varchar NOT NULL DEFAULT '',
    "referral_date" date NULL,
    "requested_by_date" date NULL,
    "procedure_intent" varchar NOT NULL DEFAULT '',
    "primary_indication" varchar NOT NULL DEFAULT '',
    "clinical_question" varchar NOT NULL DEFAULT '',
    "relevant_history" varchar NOT NULL DEFAULT '',
    "suspected_raised_intracranial_pressure" boolean NOT NULL DEFAULT false,
    "focal_neurological_signs" boolean NOT NULL DEFAULT false,
    "reduced_consciousness" boolean NOT NULL DEFAULT false,
    "ct_head_status" varchar NOT NULL DEFAULT '',
    "taking_anticoagulant" boolean NOT NULL DEFAULT false,
    "anticoagulant_agent" varchar NOT NULL DEFAULT '',
    "taking_antiplatelet" boolean NOT NULL DEFAULT false,
    "antiplatelet_agent" varchar NOT NULL DEFAULT '',
    "inr" double precision NULL,
    "platelet_count" double precision NULL,
    "bleeding_disorder" boolean NOT NULL DEFAULT false,
    "local_skin_infection" boolean NOT NULL DEFAULT false,
    "opening_pressure_required" boolean NOT NULL DEFAULT false,
    "urgency" varchar NOT NULL DEFAULT 'routine',
    "supervising_consultant" varchar NOT NULL DEFAULT '',
    "requester_contact" varchar NOT NULL DEFAULT '',
    "notes" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-lumbar_puncture_test_requests-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-lumbar_puncture_test_requests-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE
);


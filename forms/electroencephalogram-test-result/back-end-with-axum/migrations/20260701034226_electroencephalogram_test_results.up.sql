CREATE TABLE IF NOT EXISTS "electroencephalogram_test_results" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "originating_request_reference" varchar NOT NULL DEFAULT '',
    "report_status" varchar NOT NULL DEFAULT '',
    "performed_date" date NULL,
    "reported_date" date NULL,
    "eeg_type" varchar NOT NULL DEFAULT '',
    "recording_duration_minutes" double precision NULL,
    "recording_quality" varchar NOT NULL DEFAULT '',
    "clinical_history" varchar NOT NULL DEFAULT '',
    "comparison_with_previous" varchar NOT NULL DEFAULT '',
    "background_rhythm" varchar NOT NULL DEFAULT '',
    "epileptiform_discharges" boolean NOT NULL DEFAULT false,
    "focal_slowing" boolean NOT NULL DEFAULT false,
    "generalised_slowing" boolean NOT NULL DEFAULT false,
    "seizure_recorded" boolean NOT NULL DEFAULT false,
    "status_epilepticus" boolean NOT NULL DEFAULT false,
    "photoparoxysmal_response" boolean NOT NULL DEFAULT false,
    "normal_eeg" boolean NOT NULL DEFAULT false,
    "findings_narrative" varchar NOT NULL DEFAULT '',
    "clinical_correlation" varchar NOT NULL DEFAULT '',
    "impression" varchar NOT NULL DEFAULT '',
    "reporting_category" varchar NOT NULL DEFAULT '',
    "recommended_follow_up" varchar NOT NULL DEFAULT '',
    "critical_result_communicated" boolean NOT NULL DEFAULT false,
    "reported_to" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-electroencephalogram_test_results-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-electroencephalogram_test_results-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE
);


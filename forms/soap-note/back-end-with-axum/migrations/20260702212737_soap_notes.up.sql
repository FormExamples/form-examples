CREATE TABLE IF NOT EXISTS "soap_notes" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "encountered_at" timestamp with time zone NULL,
    "care_setting" varchar NOT NULL DEFAULT '',
    "encounter_type" varchar NOT NULL DEFAULT '',
    "clinician_role" varchar NOT NULL DEFAULT '',
    "patient_identifier" varchar NOT NULL DEFAULT '',
    "presenting_complaint" text NOT NULL DEFAULT '',
    "history_of_presenting_complaint" text NOT NULL DEFAULT '',
    "patient_reported_symptoms" text NOT NULL DEFAULT '',
    "relevant_history" text NOT NULL DEFAULT '',
    "red_flag_symptoms" varchar NOT NULL DEFAULT '',
    "examination_findings" text NOT NULL DEFAULT '',
    "vital_signs" text NOT NULL DEFAULT '',
    "abnormal_vitals_present" varchar NOT NULL DEFAULT '',
    "investigation_results" text NOT NULL DEFAULT '',
    "primary_diagnosis" text NOT NULL DEFAULT '',
    "problem_list" text NOT NULL DEFAULT '',
    "differential" text NOT NULL DEFAULT '',
    "clinical_impression" text NOT NULL DEFAULT '',
    "investigations_plan" text NOT NULL DEFAULT '',
    "treatment_plan" text NOT NULL DEFAULT '',
    "referrals" text NOT NULL DEFAULT '',
    "follow_up" text NOT NULL DEFAULT '',
    "safety_netting" text NOT NULL DEFAULT '',
    "managed_at_home" varchar NOT NULL DEFAULT '',
    "clinical_note" text NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NULL,
    CONSTRAINT "fk-soap_notes-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-soap_notes-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE SET NULL ON UPDATE NO ACTION
);


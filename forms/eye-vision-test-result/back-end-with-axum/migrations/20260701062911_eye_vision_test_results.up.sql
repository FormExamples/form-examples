CREATE TABLE IF NOT EXISTS "eye_vision_test_results" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "originating_request_reference" varchar NOT NULL DEFAULT '',
    "report_status" varchar NOT NULL DEFAULT '',
    "test_type" varchar NOT NULL DEFAULT '',
    "performed_date" date NULL,
    "reported_date" date NULL,
    "clinical_history" varchar NOT NULL DEFAULT '',
    "visual_acuity_right" varchar NOT NULL DEFAULT '',
    "visual_acuity_left" varchar NOT NULL DEFAULT '',
    "intraocular_pressure_right_mmhg" double precision NULL,
    "intraocular_pressure_left_mmhg" double precision NULL,
    "visual_field_result" varchar NOT NULL DEFAULT '',
    "reduced_visual_acuity" boolean NOT NULL DEFAULT false,
    "visual_field_defect" boolean NOT NULL DEFAULT false,
    "raised_intraocular_pressure" boolean NOT NULL DEFAULT false,
    "diabetic_retinopathy" boolean NOT NULL DEFAULT false,
    "optic_disc_abnormality" boolean NOT NULL DEFAULT false,
    "macular_abnormality" boolean NOT NULL DEFAULT false,
    "normal_examination" boolean NOT NULL DEFAULT false,
    "retinopathy_grade" varchar NOT NULL DEFAULT '',
    "findings_narrative" varchar NOT NULL DEFAULT '',
    "impression" varchar NOT NULL DEFAULT '',
    "reporting_category" varchar NOT NULL DEFAULT '',
    "recommended_follow_up" varchar NOT NULL DEFAULT '',
    "critical_result_communicated" boolean NOT NULL DEFAULT false,
    "reported_to" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-eye_vision_test_results-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-eye_vision_test_results-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE
);


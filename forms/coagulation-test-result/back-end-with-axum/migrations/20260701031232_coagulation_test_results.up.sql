CREATE TABLE IF NOT EXISTS "coagulation_test_results" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "originating_request_reference" varchar NOT NULL DEFAULT '',
    "report_status" varchar NOT NULL DEFAULT '',
    "performed_date" date NULL,
    "reported_date" date NULL,
    "specimen_condition" varchar NOT NULL DEFAULT '',
    "clinical_history" varchar NOT NULL DEFAULT '',
    "on_anticoagulant" boolean NOT NULL DEFAULT false,
    "anticoagulant_agent" varchar NOT NULL DEFAULT '',
    "prothrombin_time_seconds" double precision NULL,
    "inr" double precision NULL,
    "activated_partial_thromboplastin_time_seconds" double precision NULL,
    "aptt_ratio" double precision NULL,
    "fibrinogen_g_l" double precision NULL,
    "d_dimer" double precision NULL,
    "thrombin_time_seconds" double precision NULL,
    "factor_assays" varchar NOT NULL DEFAULT '',
    "overall_result_status" varchar NOT NULL DEFAULT '',
    "critical_value_present" boolean NOT NULL DEFAULT false,
    "critical_value_detail" varchar NOT NULL DEFAULT '',
    "findings_narrative" varchar NOT NULL DEFAULT '',
    "comparison_with_previous" varchar NOT NULL DEFAULT '',
    "impression" varchar NOT NULL DEFAULT '',
    "reporting_category" varchar NOT NULL DEFAULT '',
    "recommended_follow_up" varchar NOT NULL DEFAULT '',
    "critical_result_communicated" boolean NOT NULL DEFAULT false,
    "reported_to" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-coagulation_test_results-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-coagulation_test_results-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE
);


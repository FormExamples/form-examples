CREATE TABLE IF NOT EXISTS "dexa_bone_density_test_results" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "originating_request_reference" varchar NOT NULL DEFAULT '',
    "report_status" varchar NOT NULL DEFAULT '',
    "performed_date" date NULL,
    "reported_date" date NULL,
    "scan_region" varchar NOT NULL DEFAULT '',
    "examination_adequacy" varchar NOT NULL DEFAULT '',
    "clinical_history" varchar NOT NULL DEFAULT '',
    "lumbar_spine_t_score" double precision NULL,
    "lumbar_spine_z_score" double precision NULL,
    "femoral_neck_t_score" double precision NULL,
    "femoral_neck_z_score" double precision NULL,
    "total_hip_t_score" double precision NULL,
    "lowest_t_score" double precision NULL,
    "bone_mineral_density_g_cm2" double precision NULL,
    "who_classification" varchar NOT NULL DEFAULT '',
    "frax_major_fracture_percent" double precision NULL,
    "frax_hip_fracture_percent" double precision NULL,
    "vertebral_fracture_identified" boolean NOT NULL DEFAULT false,
    "comparison_with_previous" varchar NOT NULL DEFAULT '',
    "percent_change_since_previous" double precision NULL,
    "impression" varchar NOT NULL DEFAULT '',
    "recommended_follow_up" varchar NOT NULL DEFAULT '',
    "critical_result_communicated" boolean NOT NULL DEFAULT false,
    "reported_to" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-dexa_bone_density_test_results-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-dexa_bone_density_test_results-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE

CREATE TABLE IF NOT EXISTS "holter_monitor_test_results" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "originating_request_reference" varchar NOT NULL DEFAULT '',
    "report_status" varchar NOT NULL DEFAULT '',
    "monitor_type" varchar NOT NULL DEFAULT '',
    "performed_date" date NULL,
    "reported_date" date NULL,
    "recording_duration_hours" double precision NULL,
    "analysed_percent" double precision NULL,
    "clinical_history" varchar NOT NULL DEFAULT '',
    "predominant_rhythm" varchar NOT NULL DEFAULT '',
    "mean_heart_rate_bpm" integer NULL,
    "minimum_heart_rate_bpm" integer NULL,
    "maximum_heart_rate_bpm" integer NULL,
    "longest_pause_seconds" double precision NULL,
    "ventricular_ectopic_percent" double precision NULL,
    "supraventricular_ectopic_percent" double precision NULL,
    "atrial_fibrillation_detected" boolean NOT NULL DEFAULT false,
    "significant_pauses" boolean NOT NULL DEFAULT false,
    "ventricular_tachycardia" boolean NOT NULL DEFAULT false,
    "supraventricular_tachycardia" boolean NOT NULL DEFAULT false,
    "high_grade_av_block" boolean NOT NULL DEFAULT false,
    "symptom_rhythm_correlation" boolean NOT NULL DEFAULT false,
    "normal_study" boolean NOT NULL DEFAULT false,
    "findings_narrative" varchar NOT NULL DEFAULT '',
    "comparison_with_previous" varchar NOT NULL DEFAULT '',
    "impression" varchar NOT NULL DEFAULT '',
    "reporting_category" varchar NOT NULL DEFAULT '',
    "recommended_follow_up" varchar NOT NULL DEFAULT '',
    "critical_result_communicated" boolean NOT NULL DEFAULT false,
    "reported_to" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-holter_monitor_test_results-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-holter_monitor_test_results-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE
);


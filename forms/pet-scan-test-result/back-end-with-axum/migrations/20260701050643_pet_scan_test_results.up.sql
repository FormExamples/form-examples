CREATE TABLE IF NOT EXISTS "pet_scan_test_results" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "originating_request_reference" varchar NOT NULL DEFAULT '',
    "scan_type" varchar NOT NULL DEFAULT '',
    "report_status" varchar NOT NULL DEFAULT '',
    "performed_date" date NULL,
    "reported_date" date NULL,
    "clinical_history" varchar NOT NULL DEFAULT '',
    "blood_glucose_mmol_l" double precision NULL,
    "injected_activity_mbq" double precision NULL,
    "examination_adequacy" varchar NOT NULL DEFAULT '',
    "findings_narrative" varchar NOT NULL DEFAULT '',
    "hypermetabolic_lesion" boolean NOT NULL DEFAULT false,
    "nodal_uptake" boolean NOT NULL DEFAULT false,
    "distant_metastasis" boolean NOT NULL DEFAULT false,
    "no_abnormal_uptake" boolean NOT NULL DEFAULT false,
    "physiological_uptake_only" boolean NOT NULL DEFAULT false,
    "incidental_finding" boolean NOT NULL DEFAULT false,
    "suv_max" double precision NULL,
    "largest_lesion_size_mm" double precision NULL,
    "comparison_with_previous" varchar NOT NULL DEFAULT '',
    "treatment_response" varchar NOT NULL DEFAULT '',
    "impression" varchar NOT NULL DEFAULT '',
    "reporting_category" varchar NOT NULL DEFAULT '',
    "recommended_follow_up" varchar NOT NULL DEFAULT '',
    "critical_result_communicated" boolean NOT NULL DEFAULT false,
    "reported_to" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-pet_scan_test_results-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-pet_scan_test_results-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE
);

ALTER TABLE pet_scan_test_results ALTER COLUMN id SET DEFAULT gen_random_uuid();

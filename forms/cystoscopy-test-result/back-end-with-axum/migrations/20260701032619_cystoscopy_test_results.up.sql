CREATE TABLE IF NOT EXISTS "cystoscopy_test_results" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "originating_request_reference" varchar NOT NULL DEFAULT '',
    "report_status" varchar NOT NULL DEFAULT '',
    "performed_date" date NULL,
    "reported_date" date NULL,
    "procedure" varchar NOT NULL DEFAULT '',
    "anaesthesia" varchar NOT NULL DEFAULT '',
    "clinical_history" varchar NOT NULL DEFAULT '',
    "bladder_tumour" boolean NOT NULL DEFAULT false,
    "inflammation_cystitis" boolean NOT NULL DEFAULT false,
    "bladder_stones" boolean NOT NULL DEFAULT false,
    "urethral_stricture" boolean NOT NULL DEFAULT false,
    "trabeculation" boolean NOT NULL DEFAULT false,
    "prostatic_enlargement" boolean NOT NULL DEFAULT false,
    "normal_examination" boolean NOT NULL DEFAULT false,
    "tumour_size_mm" double precision NULL,
    "tumour_appearance" varchar NOT NULL DEFAULT '',
    "biopsy_taken" boolean NOT NULL DEFAULT false,
    "complication" varchar NOT NULL DEFAULT '',
    "findings_narrative" varchar NOT NULL DEFAULT '',
    "impression" varchar NOT NULL DEFAULT '',
    "reporting_category" varchar NOT NULL DEFAULT '',
    "recommended_follow_up" varchar NOT NULL DEFAULT '',
    "critical_result_communicated" boolean NOT NULL DEFAULT false,
    "reported_to" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-cystoscopy_test_results-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-cystoscopy_test_results-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE
);


CREATE TABLE IF NOT EXISTS "urinalysis_test_requests" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "status" varchar NOT NULL DEFAULT 'draft',
    "site_name" varchar NOT NULL DEFAULT '',
    "setting" varchar NOT NULL DEFAULT '',
    "referral_date" date NULL,
    "dipstick" boolean NOT NULL DEFAULT false,
    "microscopy_culture_sensitivity" boolean NOT NULL DEFAULT false,
    "albumin_creatinine_ratio" boolean NOT NULL DEFAULT false,
    "protein_creatinine_ratio" boolean NOT NULL DEFAULT false,
    "pregnancy_test" boolean NOT NULL DEFAULT false,
    "drug_screen" boolean NOT NULL DEFAULT false,
    "cytology" boolean NOT NULL DEFAULT false,
    "twenty_four_hour_collection" boolean NOT NULL DEFAULT false,
    "primary_indication" varchar NOT NULL DEFAULT '',
    "clinical_details" varchar NOT NULL DEFAULT '',
    "symptom_dysuria" boolean NOT NULL DEFAULT false,
    "symptom_frequency" boolean NOT NULL DEFAULT false,
    "symptom_visible_haematuria" boolean NOT NULL DEFAULT false,
    "symptom_loin_pain" boolean NOT NULL DEFAULT false,
    "symptom_fever" boolean NOT NULL DEFAULT false,
    "specimen_type" varchar NOT NULL DEFAULT '',
    "specimen_collected" varchar NOT NULL DEFAULT '',
    "collection_datetime" timestamp with time zone NULL,
    "pregnant" boolean NOT NULL DEFAULT false,
    "catheterised" boolean NOT NULL DEFAULT false,
    "current_antibiotics" boolean NOT NULL DEFAULT false,
    "urgency" varchar NOT NULL DEFAULT 'routine',
    "supervising_consultant" varchar NOT NULL DEFAULT '',
    "requester_contact" varchar NOT NULL DEFAULT '',
    "notes" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-urinalysis_test_requests-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-urinalysis_test_requests-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE
);

ALTER TABLE urinalysis_test_requests ALTER COLUMN id SET DEFAULT gen_random_uuid();

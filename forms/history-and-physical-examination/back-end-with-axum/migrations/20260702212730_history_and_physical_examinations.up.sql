    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "clerked_at" timestamp with time zone NULL,
    "clinician_role" varchar NOT NULL DEFAULT '',
    "registration_number" varchar NOT NULL DEFAULT '',
    "care_setting" varchar NOT NULL DEFAULT '',
    "admission_source" varchar NOT NULL DEFAULT '',
    "patient_identifier" varchar NOT NULL DEFAULT '',
    "age_band" varchar NOT NULL DEFAULT '',
    "sex" varchar NOT NULL DEFAULT '',
    "presenting_complaint" text NOT NULL DEFAULT '',
    "history_of_presenting_complaint" text NOT NULL DEFAULT '',
    "past_medical_surgical_history" text NOT NULL DEFAULT '',
    "drug_history" text NOT NULL DEFAULT '',
    "allergy_status" varchar NOT NULL DEFAULT '',
    "allergy_detail" text NOT NULL DEFAULT '',
    "family_history" text NOT NULL DEFAULT '',
    "social_history" text NOT NULL DEFAULT '',

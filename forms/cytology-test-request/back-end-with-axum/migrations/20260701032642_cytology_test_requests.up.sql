CREATE TABLE IF NOT EXISTS "cytology_test_requests" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "status" varchar NOT NULL DEFAULT 'draft',
    "site_name" varchar NOT NULL DEFAULT '',
    "setting" varchar NOT NULL DEFAULT '',
    "referral_date" date NULL,
    "requested_by_date" date NULL,
    "specimen_type" varchar NOT NULL DEFAULT '',
    "specimen_site" varchar NOT NULL DEFAULT '',
    "primary_indication" varchar NOT NULL DEFAULT '',
    "clinical_question" varchar NOT NULL DEFAULT '',
    "clinical_details" varchar NOT NULL DEFAULT '',
    "hpv_test_requested" boolean NOT NULL DEFAULT false,
    "previous_abnormal_cytology" varchar NOT NULL DEFAULT '',
    "last_menstrual_period_date" date NULL,
    "specimen_collected" varchar NOT NULL DEFAULT '',
    "collection_datetime" timestamp with time zone NULL,
    "urgency" varchar NOT NULL DEFAULT 'routine',
    "supervising_consultant" varchar NOT NULL DEFAULT '',
    "requester_contact" varchar NOT NULL DEFAULT '',
    "notes" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-cytology_test_requests-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-cytology_test_requests-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE
);

ALTER TABLE cytology_test_requests ALTER COLUMN id SET DEFAULT gen_random_uuid();

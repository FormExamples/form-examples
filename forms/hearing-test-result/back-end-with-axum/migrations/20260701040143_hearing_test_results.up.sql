CREATE TABLE IF NOT EXISTS "hearing_test_results" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "originating_request_reference" varchar NOT NULL DEFAULT '',
    "report_status" varchar NOT NULL DEFAULT '',
    "performed_date" date NULL,
    "reported_date" date NULL,
    "test_type" varchar NOT NULL DEFAULT '',
    "test_reliability" varchar NOT NULL DEFAULT '',
    "clinical_history" varchar NOT NULL DEFAULT '',
    "pure_tone_average_right_db" double precision NULL,
    "pure_tone_average_left_db" double precision NULL,
    "hearing_loss_type_right" varchar NOT NULL DEFAULT '',
    "hearing_loss_type_left" varchar NOT NULL DEFAULT '',
    "hearing_loss_severity_right" varchar NOT NULL DEFAULT '',
    "hearing_loss_severity_left" varchar NOT NULL DEFAULT '',
    "tympanometry_type_right" varchar NOT NULL DEFAULT '',
    "tympanometry_type_left" varchar NOT NULL DEFAULT '',
    "hearing_loss_present" boolean NOT NULL DEFAULT false,
    "asymmetric_loss" boolean NOT NULL DEFAULT false,
    "sudden_sensorineural_loss" boolean NOT NULL DEFAULT false,
    "conductive_component" boolean NOT NULL DEFAULT false,
    "normal_hearing" boolean NOT NULL DEFAULT false,
    "findings_narrative" varchar NOT NULL DEFAULT '',
    "impression" varchar NOT NULL DEFAULT '',
    "reporting_category" varchar NOT NULL DEFAULT '',
    "recommended_follow_up" varchar NOT NULL DEFAULT '',
    "critical_result_communicated" boolean NOT NULL DEFAULT false,
    "reported_to" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-hearing_test_results-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-hearing_test_results-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE
);

ALTER TABLE hearing_test_results ALTER COLUMN id SET DEFAULT gen_random_uuid();

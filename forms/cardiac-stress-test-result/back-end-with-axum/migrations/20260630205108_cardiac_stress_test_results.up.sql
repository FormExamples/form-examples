CREATE TABLE IF NOT EXISTS "cardiac_stress_test_results" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "originating_request_reference" varchar NOT NULL DEFAULT '',
    "report_status" varchar NOT NULL DEFAULT '',
    "performed_date" date NULL,
    "reported_date" date NULL,
    "test_type" varchar NOT NULL DEFAULT '',
    "protocol" varchar NOT NULL DEFAULT '',
    "clinical_history" varchar NOT NULL DEFAULT '',
    "comparison_with_previous" varchar NOT NULL DEFAULT '',
    "maximum_heart_rate_bpm" integer NULL,
    "percent_predicted_heart_rate" double precision NULL,
    "exercise_duration_minutes" double precision NULL,
    "mets_achieved" double precision NULL,
    "peak_blood_pressure" varchar NOT NULL DEFAULT '',
    "blood_pressure_response" varchar NOT NULL DEFAULT '',
    "ischaemic_st_changes" boolean NOT NULL DEFAULT false,
    "chest_pain_induced" boolean NOT NULL DEFAULT false,
    "arrhythmia_induced" boolean NOT NULL DEFAULT false,
    "terminated_early" boolean NOT NULL DEFAULT false,
    "test_positive" boolean NOT NULL DEFAULT false,
    "test_negative" boolean NOT NULL DEFAULT false,
    "test_inconclusive" boolean NOT NULL DEFAULT false,
    "reason_for_termination" varchar NOT NULL DEFAULT '',
    "duke_treadmill_score" double precision NULL,
    "impression" varchar NOT NULL DEFAULT '',
    "reporting_category" varchar NOT NULL DEFAULT '',
    "recommended_follow_up" varchar NOT NULL DEFAULT '',
    "critical_result_communicated" boolean NOT NULL DEFAULT false,
    "reported_to" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-cardiac_stress_test_results-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-cardiac_stress_test_results-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE
);


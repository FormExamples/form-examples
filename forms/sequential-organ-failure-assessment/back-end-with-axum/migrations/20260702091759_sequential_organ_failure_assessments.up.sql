CREATE TABLE IF NOT EXISTS "sequential_organ_failure_assessments" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "assessor_name" varchar NOT NULL DEFAULT '',
    "assessor_role" varchar NOT NULL DEFAULT '',
    "assessor_registration_number" varchar NOT NULL DEFAULT '',
    "assessed_at" timestamp with time zone NULL,
    "care_location" varchar NOT NULL DEFAULT '',
    "hours_since_admission" integer NULL,
    "patient_identifier" varchar NOT NULL DEFAULT '',
    "age_years" integer NULL,
    "sex" varchar NOT NULL DEFAULT '',
    "admission_diagnosis" text NOT NULL DEFAULT '',
    "suspected_infection" varchar NOT NULL DEFAULT '',
    "baseline_sofa_total" integer NULL,
    "pao2" double precision NULL,

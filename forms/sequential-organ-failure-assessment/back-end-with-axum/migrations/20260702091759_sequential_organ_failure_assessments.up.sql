    "platelets" double precision NULL,
    "bilirubin" double precision NULL,
    "map" double precision NULL,
    "vasopressor" varchar NOT NULL DEFAULT '',
    "vasopressor_dose" double precision NULL,
    "glasgow_coma_scale" integer NULL,
    "sedated" boolean NOT NULL DEFAULT false,
    "creatinine" double precision NULL,
    "urine_output" integer NULL,

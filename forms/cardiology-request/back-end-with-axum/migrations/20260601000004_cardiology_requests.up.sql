CREATE TABLE IF NOT EXISTS "cardiology_requests" (
    "id" uuid NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,
    "created_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updated_at" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "deleted_at" timestamp with time zone NULL,
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    "status" varchar NOT NULL,
    "site_name" varchar NOT NULL,
    "setting" varchar NOT NULL,
    "referral_date" date NULL,
    "requested_by_date" date NULL,
    "requested_service" varchar NOT NULL,
    "referral_reason" varchar NOT NULL,
    "clinical_question" varchar NOT NULL,
    "relevant_history" varchar NOT NULL,
    "symptom_chest_pain" boolean NOT NULL,
    "chest_pain_character" varchar NOT NULL,
    "symptom_breathlessness" boolean NOT NULL,
    "nyha_class" varchar NOT NULL,
    "symptom_palpitations" boolean NOT NULL,
    "symptom_syncope" boolean NOT NULL,
    "symptom_oedema" boolean NOT NULL,
    "suspected_acs" boolean NOT NULL,
    "exertional_syncope" boolean NOT NULL,
    "new_onset_heart_failure" boolean NOT NULL,
    "ecg_done" boolean NOT NULL,
    "ecg_findings" varchar NOT NULL,
    "troponin_status" varchar NOT NULL,
    "bnp_status" varchar NOT NULL,
    "known_coronary_artery_disease" boolean NOT NULL,
    "previous_mi" boolean NOT NULL,
    "heart_failure" boolean NOT NULL,
    "valve_disease" boolean NOT NULL,
    "arrhythmia" boolean NOT NULL,
    "hypertension" boolean NOT NULL,
    "diabetes" boolean NOT NULL,
    "current_medications" varchar NOT NULL,
    "urgency" varchar NOT NULL,
    "supervising_consultant" varchar NOT NULL,
    "requester_contact" varchar NOT NULL,
    "notes" varchar NOT NULL,
    CONSTRAINT "fk_cardiology_requests_patient_id" FOREIGN KEY ("patient_id") REFERENCES "patients" ("id") ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk_cardiology_requests_clinician_id" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" ("id") ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE INDEX IF NOT EXISTS "index_cardiology_request_patient_id" ON "cardiology_requests" ("patient_id");

CREATE INDEX IF NOT EXISTS "index_cardiology_request_clinician_id" ON "cardiology_requests" ("clinician_id");

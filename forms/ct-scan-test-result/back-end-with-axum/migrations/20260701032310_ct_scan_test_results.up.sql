CREATE TABLE IF NOT EXISTS "ct_scan_test_results" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "originating_request_reference" varchar NOT NULL DEFAULT '',
    "report_status" varchar NOT NULL DEFAULT '',
    "performed_date" date NULL,
    "reported_date" date NULL,
    "body_region" varchar NOT NULL DEFAULT '',
    "contrast_used" varchar NOT NULL DEFAULT '',
    "technique" varchar NOT NULL DEFAULT '',
    "examination_adequacy" varchar NOT NULL DEFAULT '',
    "clinical_history" varchar NOT NULL DEFAULT '',
    "comparison_with_previous" varchar NOT NULL DEFAULT '',
    "findings_narrative" varchar NOT NULL DEFAULT '',
    "acute_finding" boolean NOT NULL DEFAULT false,
    "mass_or_lesion" boolean NOT NULL DEFAULT false,
    "haemorrhage" boolean NOT NULL DEFAULT false,
    "infarct" boolean NOT NULL DEFAULT false,
    "fracture" boolean NOT NULL DEFAULT false,
    "infection_inflammation" boolean NOT NULL DEFAULT false,
    "obstruction" boolean NOT NULL DEFAULT false,
    "incidental_finding" boolean NOT NULL DEFAULT false,
    "largest_lesion_size_mm" double precision NULL,
    "radiation_dose_dlp" double precision NULL,
    "impression" varchar NOT NULL DEFAULT '',
    "recommended_follow_up" varchar NOT NULL DEFAULT '',
    "critical_result_communicated" boolean NOT NULL DEFAULT false,
    "reported_to" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-ct_scan_test_results-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-ct_scan_test_results-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE
);

ALTER TABLE ct_scan_test_results ALTER COLUMN id SET DEFAULT gen_random_uuid();

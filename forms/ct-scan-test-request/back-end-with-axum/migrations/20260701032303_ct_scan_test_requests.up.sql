CREATE TABLE IF NOT EXISTS "ct_scan_test_requests" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "status" varchar NOT NULL DEFAULT 'draft',
    "site_name" varchar NOT NULL DEFAULT '',
    "setting" varchar NOT NULL DEFAULT '',
    "referral_date" date NULL,
    "requested_by_date" date NULL,
    "body_region" varchar NOT NULL DEFAULT '',
    "primary_indication" varchar NOT NULL DEFAULT '',
    "clinical_question" varchar NOT NULL DEFAULT '',
    "relevant_history" varchar NOT NULL DEFAULT '',
    "contrast_required" varchar NOT NULL DEFAULT '',
    "pregnancy_status" varchar NOT NULL DEFAULT '',
    "egfr" double precision NULL,
    "previous_contrast_reaction" varchar NOT NULL DEFAULT '',
    "iodine_contrast_allergy" boolean NOT NULL DEFAULT false,
    "metformin" boolean NOT NULL DEFAULT false,
    "diabetes" boolean NOT NULL DEFAULT false,
    "renal_impairment" boolean NOT NULL DEFAULT false,
    "weight_kg" double precision NULL,
    "relevant_previous_imaging" varchar NOT NULL DEFAULT '',
    "urgency" varchar NOT NULL DEFAULT 'routine',
    "supervising_consultant" varchar NOT NULL DEFAULT '',
    "ir_me_r_justification" varchar NOT NULL DEFAULT '',
    "notes" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-ct_scan_test_requests-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-ct_scan_test_requests-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE
);

ALTER TABLE ct_scan_test_requests ALTER COLUMN id SET DEFAULT gen_random_uuid();

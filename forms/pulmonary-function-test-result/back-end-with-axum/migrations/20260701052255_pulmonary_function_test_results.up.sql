CREATE TABLE IF NOT EXISTS "pulmonary_function_test_results" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "originating_request_reference" varchar NOT NULL DEFAULT '',
    "test_type" varchar NOT NULL DEFAULT '',
    "performed_date" date NULL,
    "reported_date" date NULL,
    "report_status" varchar NOT NULL DEFAULT '',
    "test_quality" varchar NOT NULL DEFAULT '',
    "clinical_history" varchar NOT NULL DEFAULT '',
    "fev1_litres" double precision NULL,
    "fev1_percent_predicted" double precision NULL,
    "fvc_litres" double precision NULL,
    "fvc_percent_predicted" double precision NULL,
    "fev1_fvc_ratio" double precision NULL,
    "peak_expiratory_flow" double precision NULL,
    "dlco_percent_predicted" double precision NULL,
    "ventilatory_pattern" varchar NOT NULL DEFAULT '',
    "severity" varchar NOT NULL DEFAULT '',
    "bronchodilator_reversibility" varchar NOT NULL DEFAULT '',
    "airflow_obstruction" boolean NOT NULL DEFAULT false,
    "restriction" boolean NOT NULL DEFAULT false,
    "reduced_gas_transfer" boolean NOT NULL DEFAULT false,
    "significant_reversibility" boolean NOT NULL DEFAULT false,
    "normal_spirometry" boolean NOT NULL DEFAULT false,
    "findings_narrative" varchar NOT NULL DEFAULT '',
    "comparison_with_previous" varchar NOT NULL DEFAULT '',
    "impression" varchar NOT NULL DEFAULT '',
    "reporting_category" varchar NOT NULL DEFAULT '',
    "recommended_follow_up" varchar NOT NULL DEFAULT '',
    "critical_result_communicated" boolean NOT NULL DEFAULT false,
    "reported_to" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-pulmonary_function_test_results-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-pulmonary_function_test_results-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE
);


// Display label and Lily-token colour helpers for the Coagulation Test Request
// grade. Colours are Lily Design System utility tokens only (no hardcoded
// palette): success / warning / error / info / base-300.

import type {
	AppropriatenessBand,
	PreanalyticalBand,
	TriageTier,
	Recommendation
} from './types';

// ──────────────────────────────────────────────
// Display labels
// ──────────────────────────────────────────────

/** Title-case a hyphen/underscore-delimited token. */
export function titleCase(value: string): string {
	return String(value || '')
		.replace(/[-_]/g, ' ')
		.replace(/\b\w/g, (c) => c.toUpperCase());
}

/** Axis A appropriateness display label. */
export function appropriatenessLabel(value: string): string {
	switch (value) {
		case 'usually-appropriate':
			return 'Usually appropriate';
		case 'may-be-appropriate':
			return 'May be appropriate';
		case 'usually-not-appropriate':
			return 'Usually not appropriate';
		default:
			return 'Not graded';
	}
}


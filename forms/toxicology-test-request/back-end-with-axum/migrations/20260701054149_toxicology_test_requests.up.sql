CREATE TABLE IF NOT EXISTS "toxicology_test_requests" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "status" varchar NOT NULL DEFAULT 'draft',
    "site_name" varchar NOT NULL DEFAULT '',
    "setting" varchar NOT NULL DEFAULT '',
    "referral_date" date NULL,
    "requested_by_date" date NULL,
    "paracetamol_level" boolean NOT NULL DEFAULT false,
    "salicylate_level" boolean NOT NULL DEFAULT false,
    "alcohol_level" boolean NOT NULL DEFAULT false,
    "drugs_of_abuse_screen" boolean NOT NULL DEFAULT false,
    "lithium_level" boolean NOT NULL DEFAULT false,
    "digoxin_level" boolean NOT NULL DEFAULT false,
    "antiepileptic_drug_level" boolean NOT NULL DEFAULT false,
    "carboxyhaemoglobin" boolean NOT NULL DEFAULT false,
    "heavy_metals" boolean NOT NULL DEFAULT false,
    "specific_drug_level" boolean NOT NULL DEFAULT false,
    "primary_indication" varchar NOT NULL DEFAULT '',
    "clinical_details" varchar NOT NULL DEFAULT '',
    "suspected_agent" varchar NOT NULL DEFAULT '',
    "time_since_ingestion_hours" double precision NULL,
    "deliberate_overdose" boolean NOT NULL DEFAULT false,
    "symptomatic" boolean NOT NULL DEFAULT false,
    "specimen_collected" varchar NOT NULL DEFAULT '',
    "collection_datetime" timestamp with time zone NULL,
    "urgency" varchar NOT NULL DEFAULT 'routine',
    "supervising_consultant" varchar NOT NULL DEFAULT '',
    "requester_contact" varchar NOT NULL DEFAULT '',
    "notes" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-toxicology_test_requests-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-toxicology_test_requests-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE
);

ALTER TABLE toxicology_test_requests ALTER COLUMN id SET DEFAULT gen_random_uuid();

use async_trait::async_trait;
use loco_rs::{
    app::{AppContext, Initializer},
    Result,
};

pub struct ViewEngineInitializer;

#[async_trait]
impl Initializer for ViewEngineInitializer {
    fn name(&self) -> String {
        "view-engine".to_string()
    }

    async fn after_routes(
        &self,
        router: axum::Router,
        _ctx: &AppContext,
    ) -> Result<axum::Router> {
        // Tera engine is initialised by Loco from the `view_engine.tera`
        // config block (see `config/*.yaml`). Templates live under
        // `templates/` and per-resource templates are generated by
        // `cargo loco generate scaffold ... --htmx`.
        Ok(router)
    }
}

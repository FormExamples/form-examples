    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "originating_request_reference" varchar NOT NULL DEFAULT '',
    "report_status" varchar NOT NULL DEFAULT '',
    "performed_date" date NULL,
    "reported_date" date NULL,
    "specimen_type" varchar NOT NULL DEFAULT '',
    "specimen_condition" varchar NOT NULL DEFAULT '',
    "clinical_history" varchar NOT NULL DEFAULT '',
    "leucocytes" varchar NOT NULL DEFAULT '',
    "nitrites" varchar NOT NULL DEFAULT '',
    "protein" varchar NOT NULL DEFAULT '',
    "blood" varchar NOT NULL DEFAULT '',
    "glucose" varchar NOT NULL DEFAULT '',
    "ketones" varchar NOT NULL DEFAULT '',
    "bilirubin" varchar NOT NULL DEFAULT '',
    "ph" double precision NULL,
    "specific_gravity" double precision NULL,
    "red_cell_count" varchar NOT NULL DEFAULT '',
    "white_cell_count" varchar NOT NULL DEFAULT '',
    "epithelial_cells" varchar NOT NULL DEFAULT '',
    "casts" varchar NOT NULL DEFAULT '',
    "organisms_seen" boolean NOT NULL DEFAULT false,
    "crystals" varchar NOT NULL DEFAULT '',
    "culture_result" varchar NOT NULL DEFAULT '',
    "organism_isolated" varchar NOT NULL DEFAULT '',
    "colony_count_cfu_ml" varchar NOT NULL DEFAULT '',
    "antibiotic_sensitivities" varchar NOT NULL DEFAULT '',
    "overall_result_status" varchar NOT NULL DEFAULT '',
    "findings_narrative" varchar NOT NULL DEFAULT '',
    "impression" varchar NOT NULL DEFAULT '',
    "reporting_category" varchar NOT NULL DEFAULT '',
    "recommended_follow_up" varchar NOT NULL DEFAULT '',
    "critical_result_communicated" boolean NOT NULL DEFAULT false,
    "reported_to" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,

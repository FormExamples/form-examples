CREATE TABLE IF NOT EXISTS "colonoscopy_test_results" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "originating_request_reference" varchar NOT NULL DEFAULT '',
    "report_status" varchar NOT NULL DEFAULT '',
    "performed_date" date NULL,
    "reported_date" date NULL,
    "procedure" varchar NOT NULL DEFAULT '',
    "extent_reached" varchar NOT NULL DEFAULT '',
    "bowel_preparation_quality" varchar NOT NULL DEFAULT '',
    "sedation_used" boolean NOT NULL DEFAULT false,
    "clinical_history" varchar NOT NULL DEFAULT '',
    "polyps_found" boolean NOT NULL DEFAULT false,
    "mass_lesion" boolean NOT NULL DEFAULT false,
    "diverticulosis" boolean NOT NULL DEFAULT false,
    "inflammation_ibd" boolean NOT NULL DEFAULT false,
    "angiodysplasia" boolean NOT NULL DEFAULT false,
    "bleeding_source_identified" boolean NOT NULL DEFAULT false,
    "normal_examination" boolean NOT NULL DEFAULT false,
    "polyp_count" integer NULL,
    "largest_polyp_mm" double precision NULL,
    "biopsy_taken" boolean NOT NULL DEFAULT false,
    "polypectomy_performed" boolean NOT NULL DEFAULT false,
    "complication" varchar NOT NULL DEFAULT '',
    "findings_narrative" varchar NOT NULL DEFAULT '',
    "impression" varchar NOT NULL DEFAULT '',
    "reporting_category" varchar NOT NULL DEFAULT '',
    "recommended_follow_up" varchar NOT NULL DEFAULT '',
    "critical_result_communicated" boolean NOT NULL DEFAULT false,
    "reported_to" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-colonoscopy_test_results-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-colonoscopy_test_results-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE

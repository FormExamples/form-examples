CREATE TABLE IF NOT EXISTS "ss5_applications" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NULL,
    "application_date" date NULL,
    "request_type" varchar NOT NULL DEFAULT '',
    "channel" varchar NOT NULL DEFAULT '',
    "previously_applied" varchar NOT NULL DEFAULT '',
    "name_change" varchar NOT NULL DEFAULT '',
    "name_change_reason" varchar NOT NULL DEFAULT '',
    "date_of_birth_correction" varchar NOT NULL DEFAULT '',
    "replacements_this_year" integer NULL,
    "replacements_lifetime" integer NULL,
    "limit_exception_reason" varchar NOT NULL DEFAULT '',
    "limit_exception_evidence" varchar NOT NULL DEFAULT '',
    "name_on_card" text NOT NULL DEFAULT '',
    "name_at_birth" text NOT NULL DEFAULT '',
    "other_names_used" text NOT NULL DEFAULT '',
    "name_on_most_recent_card" text NOT NULL DEFAULT '',
    "date_of_birth" date NULL,
    "place_of_birth_city" text NOT NULL DEFAULT '',
    "place_of_birth_region" text NOT NULL DEFAULT '',
    "sex" varchar NOT NULL DEFAULT '',
    "citizenship" varchar NOT NULL DEFAULT '',
    "non_work_reason_valid" varchar NOT NULL DEFAULT '',
    "mother_name_at_birth" text NOT NULL DEFAULT '',
    "father_name" text NOT NULL DEFAULT '',
    "state_of_residence" varchar NOT NULL DEFAULT '',
    "mailing_address" text NOT NULL DEFAULT '',
    "phone" text NOT NULL DEFAULT '',
    "identity_document" varchar NOT NULL DEFAULT '',
    "identity_document_expired" varchar NOT NULL DEFAULT '',
    "age_document" varchar NOT NULL DEFAULT '',
    "citizenship_document" varchar NOT NULL DEFAULT '',
    "citizenship_on_file" varchar NOT NULL DEFAULT '',
    "name_change_document" varchar NOT NULL DEFAULT '',
    "documents_original_or_certified" varchar NOT NULL DEFAULT '',
    "signer_relationship" varchar NOT NULL DEFAULT '',
    "signer_name" text NOT NULL DEFAULT '',
    "signer_identity_document" varchar NOT NULL DEFAULT '',
    "signature_present" varchar NOT NULL DEFAULT '',
    "applicant_deceased" varchar NOT NULL DEFAULT '',
    "death_reported_to_ssa" varchar NOT NULL DEFAULT '',
    "preparer_note" text NOT NULL DEFAULT '',
    CONSTRAINT "fk-ss5_applications-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-ss5_applications-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE SET NULL ON UPDATE NO ACTION
);


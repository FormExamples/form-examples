CREATE TABLE IF NOT EXISTS "biopsy_test_results" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "originating_request_reference" varchar NOT NULL DEFAULT '',
    "report_status" varchar NOT NULL DEFAULT '',
    "performed_date" date NULL,
    "reported_date" date NULL,
    "biopsy_site" varchar NOT NULL DEFAULT '',
    "biopsy_method" varchar NOT NULL DEFAULT '',
    "specimen_adequacy" varchar NOT NULL DEFAULT '',
    "clinical_history" varchar NOT NULL DEFAULT '',
    "comparison_with_previous" varchar NOT NULL DEFAULT '',
    "macroscopic_description" varchar NOT NULL DEFAULT '',
    "microscopic_description" varchar NOT NULL DEFAULT '',
    "diagnosis" varchar NOT NULL DEFAULT '',
    "malignancy_present" boolean NOT NULL DEFAULT false,
    "tumour_type" varchar NOT NULL DEFAULT '',
    "histological_grade" varchar NOT NULL DEFAULT '',
    "resection_margins" varchar NOT NULL DEFAULT '',
    "lymphovascular_invasion" boolean NOT NULL DEFAULT false,
    "immunohistochemistry" varchar NOT NULL DEFAULT '',
    "molecular_results" varchar NOT NULL DEFAULT '',
    "snomed_code" varchar NOT NULL DEFAULT '',
    "impression" varchar NOT NULL DEFAULT '',
    "reporting_category" varchar NOT NULL DEFAULT '',
    "recommended_follow_up" varchar NOT NULL DEFAULT '',
    "critical_result_communicated" boolean NOT NULL DEFAULT false,
    "reported_to" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-biopsy_test_results-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-biopsy_test_results-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE
);

ALTER TABLE biopsy_test_results ALTER COLUMN id SET DEFAULT gen_random_uuid();

CREATE TABLE IF NOT EXISTS "blood_cross_match_test_results" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "originating_request_reference" varchar NOT NULL DEFAULT '',
    "report_status" varchar NOT NULL DEFAULT '',
    "performed_date" date NULL,
    "reported_date" date NULL,
    "request_type" varchar NOT NULL DEFAULT '',
    "clinical_history" varchar NOT NULL DEFAULT '',
    "abo_group" varchar NOT NULL DEFAULT '',
    "rhd_group" varchar NOT NULL DEFAULT '',
    "antibody_screen_result" varchar NOT NULL DEFAULT '',
    "antibodies_identified" varchar NOT NULL DEFAULT '',
    "crossmatch_result" varchar NOT NULL DEFAULT '',
    "component" varchar NOT NULL DEFAULT '',
    "units_crossmatched" integer NULL,
    "units_available" integer NULL,
    "two_sample_rule_met" boolean NOT NULL DEFAULT false,
    "special_requirements" varchar NOT NULL DEFAULT '',
    "historical_group_concordant" boolean NOT NULL DEFAULT false,
    "overall_result_status" varchar NOT NULL DEFAULT '',
    "findings_narrative" varchar NOT NULL DEFAULT '',
    "impression" varchar NOT NULL DEFAULT '',
    "reporting_category" varchar NOT NULL DEFAULT '',
    "recommended_follow_up" varchar NOT NULL DEFAULT '',
    "critical_result_communicated" boolean NOT NULL DEFAULT false,
    "reported_to" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-blood_cross_match_test_results-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-blood_cross_match_test_results-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE
);


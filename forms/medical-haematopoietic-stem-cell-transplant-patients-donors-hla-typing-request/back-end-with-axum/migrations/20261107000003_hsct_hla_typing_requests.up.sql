    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "subject_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    "status" varchar NOT NULL DEFAULT 'draft',
    "request_date" date NULL,
    "subject_role" varchar NOT NULL DEFAULT '',
    "donor_type" varchar NOT NULL DEFAULT '',
    "hla_typing_resolution" varchar NOT NULL DEFAULT '',
    "ethnicity" varchar NOT NULL DEFAULT '',
    "clinical_details" varchar NOT NULL DEFAULT '',
    "referrer_department" varchar NOT NULL DEFAULT '',
    "referrer_organization" varchar NOT NULL DEFAULT '',
    "copy_of_report_to" varchar NOT NULL DEFAULT '',
    "report_email" text NULL,
    "recipient_family_name" varchar NOT NULL DEFAULT '',
    "recipient_given_names" varchar NOT NULL DEFAULT '',
    "recipient_medical_record_number" varchar NOT NULL DEFAULT '',
    "recipient_birth_date" date NULL,
    "relationship_to_recipient" varchar NOT NULL DEFAULT '',
    "urgent_testing" boolean NOT NULL DEFAULT FALSE,
    "urgent_testing_reason" varchar NOT NULL DEFAULT '',
    "requested_by_signed_at" timestamp with time zone NULL,
    "consent_and_identity_confirmed" boolean NOT NULL DEFAULT FALSE,
    "sample_collector_name" varchar NOT NULL DEFAULT '',
    "sample_collected_at" timestamp with time zone NULL,
    "identifiers_on_sample_count" integer NULL,
    "identifiers_on_form_count" integer NULL,
    "sample_and_form_details_match" boolean NOT NULL DEFAULT FALSE,

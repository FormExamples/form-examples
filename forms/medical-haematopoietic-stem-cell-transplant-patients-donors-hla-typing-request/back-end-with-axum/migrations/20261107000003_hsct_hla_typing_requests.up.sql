    "clotted_red_volume_ml" integer NULL,
    "samples_other_description" varchar NOT NULL DEFAULT '',
    "laboratory_recipient_identifier" varchar NOT NULL DEFAULT '',
    "laboratory_donor_identifier" varchar NOT NULL DEFAULT '',
    "laboratory_sample_number" varchar NOT NULL DEFAULT '',
    "laboratory_sample_received_at" timestamp with time zone NULL,
    "laboratory_identifiers_checked_by" varchar NOT NULL DEFAULT '',

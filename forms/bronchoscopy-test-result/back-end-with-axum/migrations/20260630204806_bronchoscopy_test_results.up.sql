CREATE TABLE IF NOT EXISTS "bronchoscopy_test_results" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "originating_request_reference" varchar NOT NULL DEFAULT '',
    "report_status" varchar NOT NULL DEFAULT '',
    "performed_date" date NULL,
    "reported_date" date NULL,
    "procedure" varchar NOT NULL DEFAULT '',
    "sedation_used" varchar NOT NULL DEFAULT '',
    "extent_examined" varchar NOT NULL DEFAULT '',
    "clinical_history" varchar NOT NULL DEFAULT '',
    "endobronchial_lesion" boolean NOT NULL DEFAULT false,
    "mucosal_abnormality" boolean NOT NULL DEFAULT false,
    "extrinsic_compression" boolean NOT NULL DEFAULT false,
    "bleeding" boolean NOT NULL DEFAULT false,
    "foreign_body" boolean NOT NULL DEFAULT false,
    "secretions_purulent" boolean NOT NULL DEFAULT false,
    "normal_examination" boolean NOT NULL DEFAULT false,
    "lesion_location" varchar NOT NULL DEFAULT '',
    "samples_taken" varchar NOT NULL DEFAULT '',
    "complication" varchar NOT NULL DEFAULT '',
    "findings_narrative" varchar NOT NULL DEFAULT '',
    "impression" varchar NOT NULL DEFAULT '',
    "reporting_category" varchar NOT NULL DEFAULT '',
    "recommended_follow_up" varchar NOT NULL DEFAULT '',
    "critical_result_communicated" boolean NOT NULL DEFAULT false,
    "reported_to" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-bronchoscopy_test_results-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-bronchoscopy_test_results-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE
);


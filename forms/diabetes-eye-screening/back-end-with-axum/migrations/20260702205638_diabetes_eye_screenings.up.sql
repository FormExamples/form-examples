CREATE TABLE IF NOT EXISTS "diabetes_eye_screenings" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "grader_name" text NOT NULL DEFAULT '',
    "grader_role" varchar NOT NULL DEFAULT '',
    "graded_at" date NULL,
    "image_captured_at" date NULL,
    "imaging_media" varchar NOT NULL DEFAULT '',
    "patient_identifier" varchar NOT NULL DEFAULT '',
    "age_band" varchar NOT NULL DEFAULT '',
    "diabetes_type" varchar NOT NULL DEFAULT '',
    "years_since_diagnosis" double precision NULL,
    "previous_screen_date" date NULL,
    "previous_screen_result" varchar NOT NULL DEFAULT '',
    "right_retinopathy_grade" varchar NOT NULL DEFAULT '',
    "right_maculopathy_grade" varchar NOT NULL DEFAULT '',
    "right_photocoagulation" varchar NOT NULL DEFAULT '',
    "right_ungradable" varchar NOT NULL DEFAULT '',
    "right_visual_acuity" text NOT NULL DEFAULT '',
    "left_retinopathy_grade" varchar NOT NULL DEFAULT '',
    "left_maculopathy_grade" varchar NOT NULL DEFAULT '',
    "left_photocoagulation" varchar NOT NULL DEFAULT '',
    "left_ungradable" varchar NOT NULL DEFAULT '',
    "left_visual_acuity" text NOT NULL DEFAULT '',
    "clinical_context" text NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NULL,
    CONSTRAINT "fk-diabetes_eye_screenings-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-diabetes_eye_screenings-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE SET NULL ON UPDATE NO ACTION
);


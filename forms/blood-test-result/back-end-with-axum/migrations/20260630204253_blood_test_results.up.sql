CREATE TABLE IF NOT EXISTS "blood_test_results" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "originating_request_reference" varchar NOT NULL DEFAULT '',
    "report_status" varchar NOT NULL DEFAULT '',
    "performed_date" date NULL,
    "reported_date" date NULL,
    "specimen_type" varchar NOT NULL DEFAULT '',
    "specimen_condition" varchar NOT NULL DEFAULT '',
    "clinical_history" varchar NOT NULL DEFAULT '',
    "haemoglobin_g_l" double precision NULL,
    "white_cell_count" double precision NULL,
    "platelets" double precision NULL,
    "neutrophils" double precision NULL,
    "sodium_mmol_l" double precision NULL,
    "potassium_mmol_l" double precision NULL,
    "urea_mmol_l" double precision NULL,
    "creatinine_umol_l" double precision NULL,
    "egfr" double precision NULL,
    "alt_u_l" double precision NULL,
    "alkaline_phosphatase" double precision NULL,
    "bilirubin_umol_l" double precision NULL,
    "albumin_g_l" double precision NULL,
    "c_reactive_protein" double precision NULL,
    "hba1c_mmol_mol" double precision NULL,
    "glucose_mmol_l" double precision NULL,
    "tsh" double precision NULL,
    "ferritin" double precision NULL,
    "inr" double precision NULL,
    "overall_result_status" varchar NOT NULL DEFAULT '',
    "abnormal_results_present" boolean NOT NULL DEFAULT false,
    "critical_value_present" boolean NOT NULL DEFAULT false,
    "critical_value_detail" varchar NOT NULL DEFAULT '',
    "findings_narrative" varchar NOT NULL DEFAULT '',
    "comparison_with_previous" varchar NOT NULL DEFAULT '',
    "impression" varchar NOT NULL DEFAULT '',
    "reporting_category" varchar NOT NULL DEFAULT '',
    "recommended_follow_up" varchar NOT NULL DEFAULT '',
    "critical_result_communicated" boolean NOT NULL DEFAULT false,
    "reported_to" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-blood_test_results-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-blood_test_results-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE
);

ALTER TABLE blood_test_results ALTER COLUMN id SET DEFAULT gen_random_uuid();

CREATE TABLE IF NOT EXISTS "nuclear_medicine_test_results" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "originating_request_reference" varchar NOT NULL DEFAULT '',
    "report_status" varchar NOT NULL DEFAULT '',
    "performed_date" date NULL,
    "reported_date" date NULL,
    "scan_type" varchar NOT NULL DEFAULT '',
    "radiopharmaceutical" varchar NOT NULL DEFAULT '',
    "injected_activity_mbq" double precision NULL,
    "examination_adequacy" varchar NOT NULL DEFAULT '',
    "clinical_history" varchar NOT NULL DEFAULT '',
    "comparison_with_previous" varchar NOT NULL DEFAULT '',
    "findings_narrative" varchar NOT NULL DEFAULT '',
    "abnormal_uptake" boolean NOT NULL DEFAULT false,
    "metastatic_pattern" boolean NOT NULL DEFAULT false,
    "perfusion_defect" boolean NOT NULL DEFAULT false,
    "photopenic_area" boolean NOT NULL DEFAULT false,
    "no_significant_abnormality" boolean NOT NULL DEFAULT false,
    "incidental_finding" boolean NOT NULL DEFAULT false,
    "ejection_fraction_percent" double precision NULL,
    "split_function_left_percent" double precision NULL,
    "split_function_right_percent" double precision NULL,
    "impression" varchar NOT NULL DEFAULT '',
    "reporting_category" varchar NOT NULL DEFAULT '',
    "recommended_follow_up" varchar NOT NULL DEFAULT '',
    "critical_result_communicated" boolean NOT NULL DEFAULT false,
    "reported_to" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-nuclear_medicine_test_results-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-nuclear_medicine_test_results-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE
);

ALTER TABLE nuclear_medicine_test_results ALTER COLUMN id SET DEFAULT gen_random_uuid();

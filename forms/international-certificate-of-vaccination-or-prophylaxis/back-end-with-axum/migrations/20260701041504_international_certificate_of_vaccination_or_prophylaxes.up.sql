CREATE TABLE IF NOT EXISTS "international_certificate_of_vaccination_or_prophylaxes" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "status" varchar NOT NULL DEFAULT 'draft',
    "issued_at" timestamp with time zone NULL,
    "revoked_at" timestamp with time zone NULL,
    "revocation_reason" text NOT NULL DEFAULT '',
    "certificate_serial_number" varchar NOT NULL DEFAULT '',
    "issuing_country_as_iso_3166_1_alpha_3" varchar NOT NULL DEFAULT '',
    "primary_language_as_bcp_47" varchar NOT NULL DEFAULT 'en',
    "secondary_language_as_bcp_47" varchar NOT NULL DEFAULT 'fr',
    "tertiary_language_as_bcp_47" varchar NOT NULL DEFAULT '',
    "destination_countries_as_iso_3166_1_alpha_3" text NOT NULL DEFAULT '',
    "planned_arrival_date" date NULL,
    "purpose_of_travel" varchar NOT NULL DEFAULT '',
    "medical_waiver" varchar NOT NULL DEFAULT '',
    "medical_waiver_reason" text NOT NULL DEFAULT '',
    "medical_waiver_signed_at" timestamp with time zone NULL,
    "declared_pregnancy" varchar NOT NULL DEFAULT '',
    "declared_breastfeeding" varchar NOT NULL DEFAULT '',
    "declared_immunosuppression" varchar NOT NULL DEFAULT '',
    "electronic_signature_data_url" text NOT NULL DEFAULT '',
    "electronic_signature_signed_at" timestamp with time zone NULL,
    "overall_valid" varchar NOT NULL DEFAULT '',
    "validity_computed_at" timestamp with time zone NULL,
    "notes" text NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    "center_id" uuid NOT NULL,
    "medical_waiver_signed_by_clinician_id" uuid NULL,
    CONSTRAINT "fk-international_certificate_of_vaccination_or_prophylaxes-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-international_certificate_of_vaccination_or_prophylaxes-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-international_certificate_of_vaccination_or_prophylaxes-center_id-to-centers" FOREIGN KEY ("center_id") REFERENCES "centers" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-international_certificate_of_vaccination_or_prophylaxes-medical_waiver_signed_by_clinician_id-to-clinicians" FOREIGN KEY ("medical_waiver_signed_by_clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE
);


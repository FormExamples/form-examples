CREATE TABLE IF NOT EXISTS "angiography_test_results" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "originating_request_reference" varchar NOT NULL DEFAULT '',
    "report_status" varchar NOT NULL DEFAULT '',
    "performed_date" date NULL,
    "reported_date" date NULL,
    "angiography_type" varchar NOT NULL DEFAULT '',
    "body_region" varchar NOT NULL DEFAULT '',
    "contrast_used" varchar NOT NULL DEFAULT '',
    "examination_adequacy" varchar NOT NULL DEFAULT '',
    "clinical_history" varchar NOT NULL DEFAULT '',
    "comparison_with_previous" varchar NOT NULL DEFAULT '',
    "findings_narrative" varchar NOT NULL DEFAULT '',
    "significant_stenosis" boolean NOT NULL DEFAULT false,
    "occlusion" boolean NOT NULL DEFAULT false,
    "aneurysm" boolean NOT NULL DEFAULT false,
    "dissection" boolean NOT NULL DEFAULT false,
    "active_extravasation" boolean NOT NULL DEFAULT false,
    "thrombus" boolean NOT NULL DEFAULT false,
    "normal_vessels" boolean NOT NULL DEFAULT false,
    "incidental_finding" boolean NOT NULL DEFAULT false,
    "max_stenosis_percent" double precision NULL,
    "intervention_performed" boolean NOT NULL DEFAULT false,
    "impression" varchar NOT NULL DEFAULT '',
    "reporting_category" varchar NOT NULL DEFAULT '',
    "recommended_follow_up" varchar NOT NULL DEFAULT '',
    "critical_result_communicated" boolean NOT NULL DEFAULT false,
    "reported_to" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-angiography_test_results-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-angiography_test_results-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE
);

ALTER TABLE angiography_test_results ALTER COLUMN id SET DEFAULT gen_random_uuid();

CREATE TABLE IF NOT EXISTS "genetic_test_results" (
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "id" uuid PRIMARY KEY,
    "deleted_at" timestamp with time zone NULL,
    "originating_request_reference" varchar NOT NULL DEFAULT '',
    "report_status" varchar NOT NULL DEFAULT '',
    "performed_date" date NULL,
    "reported_date" date NULL,
    "test_type" varchar NOT NULL DEFAULT '',
    "genes_tested" text NOT NULL DEFAULT '',
    "sample_type" varchar NOT NULL DEFAULT '',
    "clinical_history" varchar NOT NULL DEFAULT '',
    "inheritance_pattern" varchar NOT NULL DEFAULT '',
    "variants_detected" varchar NOT NULL DEFAULT '',
    "variant_classification" varchar NOT NULL DEFAULT '',
    "zygosity" varchar NOT NULL DEFAULT '',
    "pathogenic_variant_found" boolean NOT NULL DEFAULT false,
    "vus_found" boolean NOT NULL DEFAULT false,
    "carrier_status_positive" boolean NOT NULL DEFAULT false,
    "secondary_finding" boolean NOT NULL DEFAULT false,
    "no_clinically_significant_variant" boolean NOT NULL DEFAULT false,
    "interpretation" varchar NOT NULL DEFAULT '',
    "impression" varchar NOT NULL DEFAULT '',
    "reporting_category" varchar NOT NULL DEFAULT '',
    "recommended_cascade_testing" boolean NOT NULL DEFAULT false,
    "recommended_follow_up" varchar NOT NULL DEFAULT '',
    "critical_result_communicated" boolean NOT NULL DEFAULT false,
    "reported_to" varchar NOT NULL DEFAULT '',
    "patient_id" uuid NOT NULL,
    "clinician_id" uuid NOT NULL,
    CONSTRAINT "fk-genetic_test_results-patient_id-to-patients" FOREIGN KEY ("patient_id") REFERENCES "patients" (id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "fk-genetic_test_results-clinician_id-to-clinicians" FOREIGN KEY ("clinician_id") REFERENCES "clinicians" (id) ON DELETE CASCADE ON UPDATE CASCADE
);

ALTER TABLE genetic_test_results ALTER COLUMN id SET DEFAULT gen_random_uuid();

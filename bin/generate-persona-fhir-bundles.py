#!/usr/bin/env python3
"""Generate per-persona FHIR R5 Bundles from examples/personas.json.

For each persona in a form's examples/personas.json, builds a FHIR R5
Bundle (type = collection) reflecting that persona's actual filled `state`
and computed `expected` grade. This is richer than examples/fhir-bundle.json
(generated by generate-changelog-and-examples.py), which wraps the generic,
type-defaulted fhir/r5/*.json templates and carries the same placeholder
values regardless of which persona a reader has in mind.

Scope: the *-test-result form family, whose sql/ all share one shape —
patient, clinician, a single main <slug>_result table, and a
<table>_grade / _grade_rule / _grade_flag triad (Phase 13's "shared
shape", verified fleet-wide 2026-09-06). Reuses
bin/fhir-r5/generate-fhir-r5-representations.py's SQL column parser and
value-typing helpers, substituting persona state/expected values in place
of its generic guess_fhir_value() placeholders.

Mapping (deliberately not fhir-r5's per-entity classify_table() — this is a
different, persona-driven artefact, not a schema-level template):
  patient / clinician  -> Patient / Observation, copied unchanged from
                          fhir/r5/*.json (personas do not vary these fields
                          in this form family)
  main <slug>_result    -> Observation, one component per column with a
                          non-empty persona.state value (an unanswered `''`
                          / `null` field is omitted, not fabricated; a
                          column absent from state falls back to the
                          generic guessed example, as a schema-drift safety
                          net)
  <table>_grade         -> ClinicalImpression summary built from
                          persona.expected's four-axis fields
  <table>_grade_rule    -> one DetectedIssue per persona.expected.firedRules
  <table>_grade_flag    -> one DetectedIssue per persona.expected.flags

Output: examples/personas-fhir/<NN>-<slugified-persona-name>.json, one file
per persona, plus the standard AGENTS.md/CLAUDE.md/index.md/README.md doc
quartet for the new directory.

Usage:
    bin/generate-persona-fhir-bundles.py [--check] [--all|<slug>...]

With no slugs and no --all, defaults to every *-test-result form under
forms/. --all is a synonym (this generator supports only that family so
far). --check reports drift without writing (CI drift detector).
"""

import argparse
import importlib.util
import json
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
FORMS_DIR = REPO_ROOT / "forms"

# ---------- Borrow the FHIR-template generator's column parsing / typing ----

_spec = importlib.util.spec_from_file_location(
    "generate_fhir_r5_representations",
    REPO_ROOT / "bin" / "fhir-r5" / "generate-fhir-r5-representations.py",
)
fhirgen = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(fhirgen)

TIMESTAMP = fhirgen.TIMESTAMP


def to_camel(snake: str) -> str:
    parts = snake.split("_")
    return parts[0] + "".join(p.capitalize() for p in parts[1:])


def slugify(text: str) -> str:
    text = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return re.sub(r"-{2,}", "-", text)


# Boilerplate columns never surfaced as a component/summary line.
SKIP_COLUMNS = {"id", "created_at", "updated_at", "deleted_at", "graded_at", "signed_at"}


def read_sql_tables(form_dir: Path):
    """Parse every numbered sql/ migration into {table_name: [columns]}."""
    sql_dir = form_dir / "sql"
    tables: dict[str, list[dict]] = {}
    if not sql_dir.is_dir():
        return tables
    for path in sorted(f for f in sql_dir.glob("*.sql") if f.name[:1].isdigit()):
        text = path.read_text()
        for name, cols in fhirgen.parse_create_table(text):
            tables[name] = cols
    return tables


def classify_family_tables(slug: str, tables: dict[str, list[dict]]):
    """Split a *-test-result form's tables into its five known roles."""
    grade_flag = next((n for n in tables if n.endswith("_grade_flag")), None)
    grade_rule = next((n for n in tables if n.endswith("_grade_rule")), None)
    grade = next(
        (n for n in tables if n.endswith("_grade") and n not in (grade_flag, grade_rule)),
        None,
    )
    main = next(
        (n for n in tables if n not in ("patient", "clinician", grade, grade_rule, grade_flag)),
        None,
    )
    return {
        "patient": "patient" if "patient" in tables else None,
        "clinician": "clinician" if "clinician" in tables else None,
        "main": main,
        "grade": grade,
        "grade_rule": grade_rule,
        "grade_flag": grade_flag,
    }


# ---------- Resource builders driven by persona state / expected -----------


def component_value(col: dict, raw):
    """Encode one persona-supplied value into a FHIR component's valueX."""
    fhir_type = fhirgen.determine_fhir_type(col["name"], col["type"], col["check_values"])
    if fhir_type == "boolean":
        return {"valueBoolean": bool(raw)}
    if fhir_type in ("integer", "integer-score"):
        return {"valueInteger": int(raw)}
    if fhir_type == "decimal":
        return {"valueQuantity": {"value": float(raw)}}
    if fhir_type in ("date", "instant"):
        return {"valueDateTime": str(raw)}
    if fhir_type == "code" or col["check_values"]:
        return {
            "valueCodeableConcept": {
                "coding": [
                    {
                        "code": str(raw),
                        "display": fhirgen.col_name_to_display(str(raw)),
                    }
                ]
            }
        }
    return {"valueString": str(raw)}


def build_persona_observation(table_name, columns, form_slug, persona_state, res_id):
    components = []
    for col in columns:
        name = col["name"]
        if name in SKIP_COLUMNS or name.endswith("_id"):
            continue
        camel = to_camel(name)
        if camel in persona_state:
            raw = persona_state[camel]
            if raw is None or raw == "":
                continue  # unanswered, per the empty-string/null convention
            value = raw
        else:
            fhir_type = fhirgen.determine_fhir_type(name, col["type"], col["check_values"])
            value = fhirgen.guess_fhir_value(name, col["type"], col["check_values"], fhir_type)
            if value is None or value == "":
                continue
        component = {
            "code": {
                "coding": [
                    {
                        "system": f"urn:form-examples:{form_slug}",
                        "code": name,
                        "display": fhirgen.col_name_to_display(name),
                    }
                ]
            }
        }
        component.update(component_value(col, value))
        components.append(component)

    return {
        "resourceType": "Observation",
        "id": res_id,
        "meta": {
            "profile": ["http://hl7.org/fhir/StructureDefinition/Observation"],
            "lastUpdated": TIMESTAMP,
        },
        "status": "final",
        "category": [
            {
                "coding": [
                    {
                        "system": "http://terminology.hl7.org/CodeSystem/observation-category",
                        "code": "laboratory",
                        "display": "Laboratory",
                    }
                ]
            }
        ],
        "code": {
            "coding": [
                {
                    "system": f"urn:form-examples:{form_slug}",
                    "code": table_name,
                    "display": fhirgen.slug_to_title(form_slug) + " Result",
                }
            ]
        },
        "subject": {"reference": "Patient/PLACEHOLDER"},
        "effectiveDateTime": TIMESTAMP,
        "component": components,
    }


def build_persona_clinical_impression(table_name, columns, form_slug, expected, persona_name, res_id):
    summary_parts = []
    for col in columns:
        name = col["name"]
        if name in SKIP_COLUMNS or name.endswith("_id"):
            continue
        camel = to_camel(name)
        if camel not in expected:
            continue
        value = expected[camel]
        if value is None or value == "" or isinstance(value, (list, dict)):
            continue
        summary_parts.append(f"{fhirgen.col_name_to_display(name)}: {value}")

    return {
        "resourceType": "ClinicalImpression",
        "id": res_id,
        "meta": {
            "profile": ["http://hl7.org/fhir/StructureDefinition/ClinicalImpression"],
            "lastUpdated": TIMESTAMP,
        },
        "status": "completed",
        "subject": {"reference": "Patient/PLACEHOLDER"},
        "effectiveDateTime": TIMESTAMP,
        "date": TIMESTAMP,
        "description": f"{fhirgen.slug_to_title(form_slug)} grading result — {persona_name}",
        "summary": "; ".join(summary_parts) if summary_parts else "Grading complete.",
    }


SEVERITY_MAP = {"high": "high", "medium": "moderate", "low": "low"}


def build_persona_fired_rule(form_slug, rule: dict, res_id):
    return {
        "resourceType": "DetectedIssue",
        "id": res_id,
        "meta": {
            "profile": ["http://hl7.org/fhir/StructureDefinition/DetectedIssue"],
            "lastUpdated": TIMESTAMP,
        },
        "status": "final",
        "category": [
            {
                "coding": [
                    {
                        "system": f"urn:form-examples:{form_slug}",
                        "code": "grading-fired-rule",
                        "display": rule.get("category", "Grading Fired Rule"),
                    }
                ]
            }
        ],
        "code": {
            "coding": [
                {
                    "system": f"urn:form-examples:{form_slug}:rules",
                    "code": rule.get("ruleId", ""),
                    "display": rule.get("axis", "") or "Grading rule",
                }
            ]
        },
        "severity": "moderate",
        "subject": {"reference": "Patient/PLACEHOLDER"},
        "identifiedDateTime": TIMESTAMP,
        "detail": rule.get("description", ""),
    }


def build_persona_flag(form_slug, flag: dict, res_id):
    return {
        "resourceType": "DetectedIssue",
        "id": res_id,
        "meta": {
            "profile": ["http://hl7.org/fhir/StructureDefinition/DetectedIssue"],
            "lastUpdated": TIMESTAMP,
        },
        "status": "final",
        "category": [
            {
                "coding": [
                    {
                        "system": f"urn:form-examples:{form_slug}",
                        "code": "grading-additional-flag",
                        "display": flag.get("category", "Additional Safety Flag"),
                    }
                ]
            }
        ],
        "code": {
            "coding": [
                {
                    "system": f"urn:form-examples:{form_slug}:flags",
                    "code": flag.get("flagId", ""),
                    "display": flag.get("category", "Safety flag"),
                }
            ]
        },
        "severity": SEVERITY_MAP.get(str(flag.get("priority", "")), "moderate"),
        "subject": {"reference": "Patient/PLACEHOLDER"},
        "identifiedDateTime": TIMESTAMP,
        "detail": flag.get("description", ""),
        "detectedIssueManagement": [{"concept": {"text": flag.get("suggestedAction", "")}}]
        if flag.get("suggestedAction")
        else None,
    }


# ---------- Bundle assembly --------------------------------------------------


def deterministic_uuid(seed_text: str) -> str:
    """A stable, distinct UUID-shaped id derived from seed_text (not random —
    reruns of the same persona must produce byte-identical output)."""
    import hashlib

    h = hashlib.sha256(seed_text.encode()).hexdigest()
    return f"{h[0:8]}-{h[8:12]}-4{h[13:16]}-a{h[17:20]}-{h[20:32]}"


def build_persona_bundle(form_dir: Path, form_slug: str, title: str, roles: dict, tables: dict, persona: dict, idx: int):
    fhir_dir = form_dir / "fhir" / "r5"
    entries = []

    def add(resource, full_url_seed):
        full_url = f"urn:uuid:{deterministic_uuid(full_url_seed)}"
        resource["id"] = deterministic_uuid(full_url_seed)
        entries.append({"fullUrl": full_url, "resource": resource})
        return full_url

    persona_name = persona.get("name", f"persona-{idx}")
    seed_base = f"{form_slug}:{idx}:{persona_name}"

    patient_url = None
    if roles["patient"]:
        patient_path = fhir_dir / "patient.json"
        if patient_path.is_file():
            patient = json.loads(patient_path.read_text())
            patient_url = add(patient, f"{seed_base}:patient")

    if roles["clinician"]:
        clinician_path = fhir_dir / "clinician.json"
        if clinician_path.is_file():
            clinician = json.loads(clinician_path.read_text())
            # This family's persona bundle has no Encounter resource (the
            # main result table is remapped to Observation below, not
            # Encounter) — drop the generic template's now-dangling ref.
            clinician.pop("encounter", None)
            if patient_url:
                clinician["subject"] = {"reference": patient_url}
            else:
                clinician.pop("subject", None)
            add(clinician, f"{seed_base}:clinician")

    state = persona.get("state", {})
    expected = persona.get("expected", {})

    if roles["main"]:
        obs = build_persona_observation(
            roles["main"], tables[roles["main"]], form_slug, state, "PLACEHOLDER"
        )
        if patient_url:
            obs["subject"] = {"reference": patient_url}
        else:
            obs.pop("subject", None)
        add(obs, f"{seed_base}:main")

    if roles["grade"]:
        ci = build_persona_clinical_impression(
            roles["grade"], tables[roles["grade"]], form_slug, expected, persona_name, "PLACEHOLDER"
        )
        if patient_url:
            ci["subject"] = {"reference": patient_url}
        else:
            ci.pop("subject", None)
        add(ci, f"{seed_base}:grade")

    for i, rule in enumerate(expected.get("firedRules", []) or []):
        issue = build_persona_fired_rule(form_slug, rule, "PLACEHOLDER")
        if patient_url:
            issue["subject"] = {"reference": patient_url}
        else:
            issue.pop("subject", None)
        add(issue, f"{seed_base}:rule:{i}:{rule.get('ruleId', i)}")

    for i, flag in enumerate(expected.get("flags", []) or []):
        issue = build_persona_flag(form_slug, flag, "PLACEHOLDER")
        if issue.get("detectedIssueManagement") is None:
            issue.pop("detectedIssueManagement", None)
        if patient_url:
            issue["subject"] = {"reference": patient_url}
        else:
            issue.pop("subject", None)
        add(issue, f"{seed_base}:flag:{i}:{flag.get('flagId', i)}")

    return {
        "resourceType": "Bundle",
        "id": deterministic_uuid(f"{seed_base}:bundle"),
        "type": "collection",
        "timestamp": TIMESTAMP,
        "meta": {
            "profile": ["http://hl7.org/fhir/StructureDefinition/Bundle"],
            "tag": [
                {
                    "system": "https://github.com/joelparkerhenderson/form-examples",
                    "code": "example",
                    "display": f"{title} — {persona_name} persona bundle",
                }
            ],
        },
        "entry": entries,
    }


# ---------- File I/O ----------------------------------------------------


DOC_INDEX_MD = """# {title} — examples/personas-fhir/

One FHIR R5 `Bundle` (type = `collection`) per entry in
[`../personas.json`](../personas.json), built from that persona's actual
filled `state` and computed `expected` grade — richer than the generic,
type-defaulted [`../fhir-bundle.json`](../fhir-bundle.json).

Generated by `bin/generate-persona-fhir-bundles.py`; run with `--check` in
CI to detect drift. Never hand-edit these files.
"""

DOC_AGENTS_MD = """# {title} — examples/personas-fhir/

Generated per-persona FHIR R5 Bundles. See [`index.md`](index.md). Never
hand-edit — regenerate with `bin/generate-persona-fhir-bundles.py`.
"""


def write_if_changed(path: Path, content: str, check: bool, drifted: list) -> None:
    existing = path.read_text() if path.is_file() else None
    if existing == content:
        return
    drifted.append(path)
    if not check:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)


def write_docs(out_dir: Path, title: str, check: bool, drifted: list) -> None:
    write_if_changed(out_dir / "index.md", DOC_INDEX_MD.format(title=title), check, drifted)
    write_if_changed(out_dir / "AGENTS.md", DOC_AGENTS_MD.format(title=title), check, drifted)
    write_if_changed(out_dir / "CLAUDE.md", "@AGENTS.md\n", check, drifted)
    readme = out_dir / "README.md"
    if check:
        if not readme.is_symlink() or not readme.is_file():
            drifted.append(readme)
    else:
        out_dir.mkdir(parents=True, exist_ok=True)
        if readme.is_symlink() or readme.exists():
            readme.unlink()
        readme.symlink_to("index.md")


def process_form(form_dir: Path, check: bool, drifted: list) -> int:
    slug = form_dir.name
    personas_path = form_dir / "examples" / "personas.json"
    if not personas_path.is_file():
        return 0
    tables = read_sql_tables(form_dir)
    roles = classify_family_tables(slug, tables)
    if not roles["main"] or not roles["grade"]:
        print(f"SKIP {slug}: does not match the *-test-result shape", file=sys.stderr)
        return 0

    data = json.loads(personas_path.read_text())
    personas = data.get("personas", [])
    if not personas:
        return 0

    title = fhirgen.slug_to_title(slug)
    out_dir = form_dir / "examples" / "personas-fhir"
    write_docs(out_dir, title, check, drifted)

    count = 0
    for idx, persona in enumerate(personas, start=1):
        bundle = build_persona_bundle(form_dir, slug, title, roles, tables, persona, idx)
        filename = f"{idx:02d}-{slugify(persona.get('name', f'persona-{idx}'))}.json"
        content = json.dumps(bundle, indent=2) + "\n"
        write_if_changed(out_dir / filename, content, check, drifted)
        count += 1

    # Remove stale bundle files left behind by a shrunk/renamed persona list.
    if out_dir.is_dir():
        keep = {
            f"{idx:02d}-{slugify(p.get('name', f'persona-{idx}'))}.json"
            for idx, p in enumerate(personas, start=1)
        }
        for existing in out_dir.glob("*.json"):
            if existing.name not in keep:
                drifted.append(existing)
                if not check:
                    existing.unlink()

    return count


def iter_family_forms():
    return sorted(p for p in FORMS_DIR.glob("*-test-result") if p.is_dir())


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("slugs", nargs="*", help="form slugs (default: every *-test-result form)")
    parser.add_argument("--all", action="store_true", help="same as no slugs: every *-test-result form")
    parser.add_argument("--check", action="store_true", help="report drift without writing; exit 1 if any found")
    args = parser.parse_args()

    if args.slugs:
        form_dirs = [FORMS_DIR / s for s in args.slugs]
        for d in form_dirs:
            if not d.is_dir():
                print(f"error: no such form directory: {d}", file=sys.stderr)
                return 2
    else:
        form_dirs = iter_family_forms()

    drifted: list[Path] = []
    total = 0
    for form_dir in form_dirs:
        total += process_form(form_dir, args.check, drifted)

    if args.check:
        if drifted:
            print(f"DRIFT: {len(drifted)} file(s) out of date:", file=sys.stderr)
            for p in drifted:
                print(f"  {p.relative_to(REPO_ROOT)}", file=sys.stderr)
            return 1
        print(f"OK: {total} persona bundle(s) up to date across {len(form_dirs)} form(s).")
        return 0

    print(f"Generated {total} persona bundle(s) across {len(form_dirs)} form(s) "
          f"({len(drifted)} file(s) written/updated).")
    return 0


if __name__ == "__main__":
    sys.exit(main())

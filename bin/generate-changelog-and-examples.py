CLAUDE_AT_AGENTS = "@AGENTS.md\n"


# ---------- SQL parsing ----------------------------------------------------


# Capture a single column: name, type-and-rest (until a comma at the same
# parenthesis depth or end). We then introspect type and CHECK clauses.
COLUMN_LINE_RE = re.compile(
    r"^\s*(?P<name>[a-z_][a-z0-9_]*)\s+(?P<rest>[^,\n]+(?:\([^)]*\)[^,\n]*)*),?\s*$",
    re.IGNORECASE | re.MULTILINE,
)

CREATE_TABLE_RE = re.compile(
    r"CREATE\s+TABLE\s+(?P<name>[a-z_][a-z0-9_]*)\s*\((?P<body>[\s\S]*?)\)\s*;",
    re.IGNORECASE,
)

CHECK_IN_RE = re.compile(
    r"CHECK\s*\(\s*\w+\s+IN\s*\(\s*((?:'[^']*'\s*,?\s*)+)\)\s*\)",
    re.IGNORECASE,
)
CHECK_BETWEEN_RE = re.compile(
    r"CHECK\s*\(.*?BETWEEN\s+(-?\d+(?:\.\d+)?)\s+AND\s+(-?\d+(?:\.\d+)?)\s*\)",
    re.IGNORECASE,
)

# Words that should not be treated as column names
NON_COLUMN_KEYWORDS = {
    "primary",
    "unique",
    "constraint",
    "foreign",
    "check",
    "create",
}


def parse_sql_table(sql_text: str) -> tuple[str, list[dict[str, Any]]] | None:
    m = CREATE_TABLE_RE.search(sql_text)
    if not m:
        return None
    table_name = m.group("name").lower()
    body = m.group("body")

    # Strip comments
    body = re.sub(r"--.*$", "", body, flags=re.MULTILINE)

    columns: list[dict[str, Any]] = []
    # Split on commas at parenthesis depth 0
    depth = 0
    buf: list[str] = []
    pieces: list[str] = []
    for ch in body:
        if ch == "(":
            depth += 1
            buf.append(ch)
        elif ch == ")":
            depth -= 1
            buf.append(ch)
        elif ch == "," and depth == 0:
            pieces.append("".join(buf).strip())
            buf = []
        else:
            buf.append(ch)
    if buf:
        pieces.append("".join(buf).strip())

    for piece in pieces:
        if not piece:
            continue
        first_word = piece.split()[0].lower()
        if first_word in NON_COLUMN_KEYWORDS:
            continue
        # Skip table-level constraints like UNIQUE (...), PRIMARY KEY (...)
        if re.match(r"^[A-Z]+\s*\(", piece):
            continue
        m2 = re.match(r"^([a-z_][a-z0-9_]*)\s+(.+)$", piece, re.IGNORECASE | re.DOTALL)
        if not m2:
            continue
        name = m2.group(1).lower()
        rest = m2.group(2)
        rest_upper = rest.upper()
        col_type = _detect_type(rest_upper)

        nullable = "NOT NULL" not in rest_upper
        is_pk = "PRIMARY KEY" in rest_upper
        check_in = _check_in_values(rest)
        check_between = CHECK_BETWEEN_RE.search(rest)

        columns.append(
            {
                "name": name,
                "type": col_type,
                "raw": rest.strip(),
                "nullable": nullable,
                "is_pk": is_pk,
                "check_in": check_in,
                "check_between": (
                    (float(check_between.group(1)), float(check_between.group(2)))
                    if check_between
                    else None
                ),
            }
        )

    return table_name, columns


def _detect_type(rest_upper: str) -> str:
    if "UUID" in rest_upper:
        return "uuid"
    if "TIMESTAMPTZ" in rest_upper or "TIMESTAMP WITH TIME ZONE" in rest_upper:
        return "timestamptz"
    if rest_upper.startswith("TIMESTAMP"):
        return "timestamp"
    if rest_upper.startswith("DATE"):
        return "date"
    if rest_upper.startswith("TIME"):
        return "time"
    if "BOOLEAN" in rest_upper or "BOOL " in rest_upper or rest_upper.startswith("BOOL"):
        return "boolean"
    if "SMALLINT" in rest_upper or "INTEGER" in rest_upper or rest_upper.startswith("INT"):
        return "integer"
    if "BIGINT" in rest_upper:
        return "integer"
    if "NUMERIC" in rest_upper or "DECIMAL" in rest_upper or "REAL" in rest_upper or "DOUBLE" in rest_upper:
        return "numeric"
    if "VARCHAR" in rest_upper or "TEXT" in rest_upper or "CHAR" in rest_upper:
        return "text"
    if "JSONB" in rest_upper or "JSON" in rest_upper:
        return "json"
    return "text"


def _check_in_values(rest: str) -> list[str] | None:
    m = CHECK_IN_RE.search(rest)
    if not m:
        return None
    raw = m.group(1)
    return [v.strip().strip("'") for v in re.findall(r"'([^']*)'", raw)]


def example_value(col: dict[str, Any], idx_seed: int) -> Any:
    t = col["type"]
    if col["is_pk"]:
        return _stable_uuid(idx_seed)
    if t == "uuid":
        return _stable_uuid(idx_seed)
    raw_upper = col["raw"].upper()
    if t == "timestamptz" or t == "timestamp":
        if col["nullable"] and ("DEFAULT NULL" in raw_upper or "DEFAULT" not in raw_upper):
            return None
        return EXAMPLE_TIMESTAMP
    if t == "date":
        if col["nullable"] and ("DEFAULT NULL" in raw_upper or "DEFAULT" not in raw_upper):
            return None
        return EXAMPLE_DATE
    if t == "time":
        if col["nullable"] and ("DEFAULT NULL" in raw_upper or "DEFAULT" not in raw_upper):
            return None
        return EXAMPLE_TIME
    if t == "boolean":
        return True
    if t == "integer":
        if col["check_between"]:
            lo, hi = col["check_between"]
            return int((lo + hi) // 2)
        # NULL is the convention for unanswered numeric fields
        return None if col["nullable"] else 0
    if t == "numeric":
        if col["check_between"]:
            lo, hi = col["check_between"]
            return round((lo + hi) / 2, 1)
        return None if col["nullable"] else 0.0
    if t == "json":
        return {}
    # text / enum
    if col["check_in"]:
        # Prefer the first non-empty allowed value
        for v in col["check_in"]:
            if v != "":
                return v
        return ""
    return ""


def _stable_uuid(seed: int) -> str:
    # 12 hex chars at the end; bump per call to keep IDs distinct within a doc.
    suffix = f"{seed % 0xFFFFFFFFFFFF:012x}"
    return f"{EXAMPLE_UUID_BASE[:24]}{suffix}"


def to_camel(snake: str) -> str:
    parts = snake.split("_")
    return parts[0] + "".join(p.capitalize() for p in parts[1:])


# ---------- File assembly ---------------------------------------------------


def gather_form_jsons(form_dir: Path) -> dict[str, Any]:
    """Build a single filled-form JSON by walking sql-migrations/ tables."""
    sql_dir = form_dir / "sql-migrations"
    if not sql_dir.is_dir():
        return {"_note": "no sql-migrations/ found"}

    sql_files = sorted(sql_dir.glob("*.sql"))
    tables: dict[str, Any] = {}
    seed = 1
    for path in sql_files:
        # Skip pure function / extension / index migrations
        text = path.read_text()
        for parsed in iter_tables(text):
            table_name, columns = parsed
            obj: dict[str, Any] = {}
            for col in columns:
                obj[to_camel(col["name"])] = example_value(col, seed)
                seed += 1
            tables[to_camel(table_name)] = obj
    return tables


def iter_tables(sql_text: str):
    for m in CREATE_TABLE_RE.finditer(sql_text):
        # Re-parse each table individually
        snippet = m.group(0)
        parsed = parse_sql_table(snippet)
        if parsed:
            yield parsed


def gather_fhir_bundle(form_dir: Path, title: str) -> dict[str, Any]:
    fhir_dir = form_dir / "fhir-r5"
    if not fhir_dir.is_dir():
        return {
            "resourceType": "Bundle",
            "type": "document",
            "timestamp": EXAMPLE_TIMESTAMP,
            "entry": [],
        }
    entries: list[dict[str, Any]] = []
    for path in sorted(fhir_dir.glob("*.json")):
        try:
            resource = json.loads(path.read_text())
        except json.JSONDecodeError:
            continue
        if not isinstance(resource, dict) or "resourceType" not in resource:
            continue
        rtype = resource["resourceType"]
        rid = resource.get("id", "")
        full_url = f"urn:uuid:{rid}" if rid else f"urn:uuid:{path.stem}"
        entries.append({"fullUrl": full_url, "resource": resource})

    return {
        "resourceType": "Bundle",
        "id": _stable_uuid(99),
        "type": "document",
        "timestamp": EXAMPLE_TIMESTAMP,
        "meta": {
            "profile": ["http://hl7.org/fhir/StructureDefinition/Bundle"],
            "tag": [
                {
                    "system": "https://github.com/joelparkerhenderson/form-examples",
                    "code": "example",
                    "display": f"{title} example bundle",
                }
            ],
        },
        "entry": entries,
    }


def write_if_changed(path: Path, content: str | bytes, check: bool, drifted: list[Path]) -> None:
    if isinstance(content, str):
        new_bytes = content.encode("utf-8")
    else:
        new_bytes = content
    if path.exists():
        old = path.read_bytes()
        if old == new_bytes:
            return
    if check:
        drifted.append(path)
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(new_bytes)


def write_changelog(form_dir: Path, title: str, check: bool, drifted: list[Path]) -> None:
    path = form_dir / "CHANGELOG.md"
    if path.exists():
        # Never overwrite an existing changelog — users add real entries here.
        return
    if check:
        drifted.append(path)
        return
    path.write_text(CHANGELOG_TEMPLATE.format(title=title))


def write_examples(form_dir: Path, slug: str, title: str, check: bool, drifted: list[Path]) -> None:
    examples = form_dir / "examples"
    examples.mkdir(parents=True, exist_ok=True)

    # AGENTS.md
    write_if_changed(
        examples / "AGENTS.md",
        EXAMPLES_AGENTS_TEMPLATE.format(title=title, slug=slug),
        check,
        drifted,
    )
    # CLAUDE.md
    write_if_changed(examples / "CLAUDE.md", CLAUDE_AT_AGENTS, check, drifted)
    # index.md
    write_if_changed(
        examples / "index.md", EXAMPLES_INDEX_TEMPLATE.format(title=title), check, drifted
    )
    # README.md symlink to index.md
    readme = examples / "README.md"
    if not readme.exists():
        if check:
            drifted.append(readme)
        else:
            os.symlink("index.md", readme)
    elif readme.is_symlink() and os.readlink(readme) != "index.md":
        if check:
            drifted.append(readme)
        else:
            readme.unlink()
            os.symlink("index.md", readme)

    # assessment.json — never overwrite a hand-curated fixture if it exists
    assessment_path = examples / "assessment.json"
    if not assessment_path.exists():
        data = gather_form_jsons(form_dir)
        write_if_changed(
            assessment_path,
            json.dumps(data, indent=2, ensure_ascii=False) + "\n",
            check,
            drifted,
        )

    # fhir-bundle.json — regenerate when fhir-r5/ changes
    bundle_path = examples / "fhir-bundle.json"
    bundle = gather_fhir_bundle(form_dir, title)
    write_if_changed(
        bundle_path,
        json.dumps(bundle, indent=2, ensure_ascii=False) + "\n",
        check,
        drifted,
    )


def iter_forms(slugs: list[str] | None):
    if slugs:
        for slug in slugs:
            yield slug
        return
    # Walk forms/ directly so we cover every form directory (including ones
    # not yet registered in forms.tsv). A directory is treated as a form when
    # it contains index.md, mirroring bin/generate-spec.py.
    for d in sorted(FORMS_DIR.iterdir()):
        if not d.is_dir():
            continue
        if d.name.startswith(".") or d.name in {"lily-spec", "lily-svelte-spec"}:
            continue
        if not (d / "index.md").is_file():
            continue
        yield d.name


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("slugs", nargs="*")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)

    drifted: list[Path] = []
    for slug in iter_forms(args.slugs or None):
        form_dir = FORMS_DIR / slug
        if not form_dir.is_dir():
            print(f"warning: no such form: {slug}", file=sys.stderr)
            continue
        title = read_index_title(form_dir / "index.md", slug)
        write_changelog(form_dir, title, args.check, drifted)
        write_examples(form_dir, slug, title, args.check, drifted)

    if drifted:
        print(f"drift: {len(drifted)} files would change", file=sys.stderr)
        for p in drifted[:20]:
            print(f"  {p.relative_to(REPO_ROOT)}", file=sys.stderr)
        if len(drifted) > 20:
            print(f"  ... ({len(drifted) - 20} more)", file=sys.stderr)
        return 1 if args.check else 0
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

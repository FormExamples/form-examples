def payload_fns(tail, table):
    """`ActiveModel::from_payload` becomes insert and update queries."""
    m = re.search(r"impl ActiveModel \{(.*?)pub fn from_payload\(\s*(.*?),?\s*\) -> Self \{", tail, re.S)
    if not m:
        return tail
    a, b = block(tail, tail.index("impl ActiveModel {"))
    x, y = block(tail, tail.index("Self {", m.end()))
    pairs = set_fields(tail[x + 1 : y])
    ins = [(c, e) for c, e in pairs if e != "None"]
    cols = [c for c, _ in ins]
    isql = f"INSERT INTO {table} ({', '.join(cols)}) VALUES ({', '.join(f'${n + 1}' for n in range(len(cols)))}) RETURNING *"
    sets, ub, n = [], [], 1
    for c, e in pairs:
        if c == "created_at":
            continue
        if e == "None":
            sets.append(f"{c} = NULL")
        else:
            n += 1
            sets.append(f"{c} = ${n}")
            ub.append(e)
    usql = f"UPDATE {table} SET {', '.join(sets)} WHERE id = $1 RETURNING *"
    params = " ".join(m[2].split()).rstrip(",")
    bi = "".join(f"\n            .bind({e})" for _, e in ins)
    bu = "".join(f"\n            .bind({e})" for e in ub)
    new = f'''impl Model {{
    /// Insert a row from an engine payload plus its foreign keys.
    ///
    /// # Errors
    ///
    /// Propagates the database error.
    pub async fn insert_payload(db: &PgPool, {params}) -> sqlx::Result<Self> {{
        let now = Utc::now();
        sqlx::query_as(
            {render_sql(isql, 12)},
        ){bi}
            .fetch_one(db)
            .await
    }}

    /// Overwrite a row from an engine payload, keeping its creation time.
    ///
    /// # Errors
    ///
    /// Propagates the database error.
    pub async fn update_payload(db: &PgPool, id: Uuid, {params}) -> sqlx::Result<Self> {{
        let now = Utc::now();
        sqlx::query_as(
            {render_sql(usql, 12)},
        )
            .bind(id){bu}
            .fetch_one(db)
            .await
    }}

    /// Mark a row deleted.
    ///
    /// # Errors
    ///
    /// Propagates the database error.
    pub async fn soft_delete(db: &PgPool, id: Uuid) -> sqlx::Result<()> {{
        sqlx::query("UPDATE {table} SET deleted_at = now(), updated_at = now() WHERE id = $1")
            .bind(id)
            .execute(db)
            .await?;
        Ok(())
    }}
}}'''
    return tail[:a - len("impl ActiveModel ")] + new + tail[b + 1:]


def custom_tail(old, table, p):
    """The hand-written part of a model, on sqlx."""
    m = re.search(r"impl ActiveModelBehavior for ActiveModel", old)
    _, end = block(old, m.end())
    tail = old[end + 1 :]
    tail = re.sub(r"^// implement your[^\n]*\n", "", tail, flags=re.M)
    tail = re.sub(r"^impl (Model|ActiveModel|Entity) \{\}\n", "", tail, flags=re.M)
    tail = payload_fns(tail, table)
    tail = re.sub(r"(?<![\w:])(Entity|Column)::", rf"{table}::\1::", tail)
    tail = re.sub(r"(?<![\w:])ActiveModel \{", f"{table}::ActiveModel {{", tail)
    tail = translate(tail, p).replace(f"{table}::Model", "Model")
    tail = re.sub(r"\bModel::find_by_id\(db, id\)\.await\b", "Model::find_by_id(db, id).await", tail)
    uses = "".join(u for u in re.findall(r"^use [^;]*;\n", old, re.M)
                   if not re.match(r"use (sea_orm|serde)\b", u)).replace("super::_entities", "super")
    return uses, "\n" + tail.strip() + "\n"


def convert_models(src_dir):
    models = src_dir / "models"
    ent = models / "_entities"
    for e in sorted(ent.glob("*.rs")):
        if e.name in ("mod.rs", "prelude.rs"):
            continue
        s = e.read_text()
        table = re.search(r'table_name = "(\w+)"', s)[1]
        struct = entity_struct(s)
        p = models / e.name
        old = p.read_text() if p.exists() else ""
        if e.stem == "users":
            p.write_text((HERE / "users.rs.tmpl").read_text().replace("@@STRUCT@@", struct))
            continue
        head = "".join(re.findall(r"^//![^\n]*\n", old, re.M)) or f"//! {e.stem} model.\n"
        alias = re.search(r"(///[^\n]*\n)pub type (\w+) = Entity;", old)
        a = f"{alias[1]}pub type {alias[2]} = Model;\n" if alias else ""
        p.write_text(MODEL.format(head=head + "\n", struct=struct, alias=a, table=table))
        if re.search(r"\bimpl (Model|ActiveModel|Entity) \{\s*[^\s}]", old) or re.search(r"^(pub )?(async )?fn ", old, re.M):
            print(f"  CUSTOM MODEL {p}")
            uses, tail = custom_tail(old, e.stem, p)
            body = p.read_text().replace("use crate::support::prelude::*;\n", "use crate::support::prelude::*;\n" + uses, 1)
            p.write_text(body + tail)
    shutil.rmtree(ent)
    mod = models / "mod.rs"
    mod.write_text(mod.read_text().replace("pub mod _entities;\n", ""))



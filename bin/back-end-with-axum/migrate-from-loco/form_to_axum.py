def convert_test_file(p, lib):
    s = o = p.read_text()
    s = s.replace("use loco_rs::testing::prelude::*;",
                  "use axa::testing::prelude::*;\n#[allow(unused_imports)]\nuse crate::{cleanup_user_model, db, seed};")
    s = s.replace("use loco_rs::{app::AppContext, TestServer};", "use axa::{testing::TestServer, AppContext};\nuse crate::db;")
    s = s.replace("sea_orm::prelude::Decimal", "rust_decimal::Decimal")
    s = s.replace("loco_rs::prelude::Uuid", "uuid::Uuid")
    s = s.replace("loco_rs::app::AppContext", "axa::AppContext")
    s = re.sub(r"^use sea_orm::[^\n]*\n", "", s, flags=re.M)
    s = s.replace("ctx.mailer.unwrap().deliveries()", f"{lib}::support::mailer::deliveries(&ctx)")
    s = re.sub(r"\s*\.into_active_model\(\)", "", s)
    s = re.sub(r"let boot = boot_test::<App>\(\)\s*\.await\s*\.expect\(\"Failed to boot test application\"\);\s*let invalid_user = [\w:]*ActiveModel \{.*?\};\s*let res = invalid_user\.insert\(&boot\.app_context\.db\)\.await;",
               'let res = users::validate("1", "invalid-email");', s, flags=re.S)
    assert "invalid_user" not in s, p
    s = s.replace("&boot.app_context.db", "&db(&boot.app_context)")
    if p.name == "prepare_data.rs":
        s = s.replace("&ctx.db", "&db(ctx)")
    s = s.replace("&ctx.db", "&db(&ctx)")
    if s != o:
        p.write_text(s)



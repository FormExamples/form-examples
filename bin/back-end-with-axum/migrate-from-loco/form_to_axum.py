"""Move one form's back-end crate from Loco and SeaORM to axa and sqlx."""
import re, shutil, sys, tomllib
from pathlib import Path

TABLES = set()
HERE = Path(__file__).parent


def block(src, start):
    """(open, close) offsets of the brace block opening at or after start."""
    i = src.index("{", start)
    depth, j = 0, i
    in_str = False
    while True:
        c = src[j]
        if in_str:
            if c == "\\":
                j += 1
            elif c == '"':
                in_str = False
        elif c == '"':
            in_str = True
        elif c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return i, j
        j += 1


def fn_body(src, signature):
    m = re.search(signature, src)
    if not m:
        return None
    i, j = block(src, m.end())
    return src[i + 1 : j]



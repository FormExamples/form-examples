def snake(name):
    return re.sub(r"(?<!^)([A-Z])", r"_\1", name).lower()


def to_table(path):
    return path.split("::")[-1]


def set_fields(body):
    """`field: ActiveValue::Set(expr)` pairs from an ActiveModel literal."""
    out = []
    for part in split_top(body):
        m = re.fullmatch(r"(\w+):\s*(?:ActiveValue::)?[Ss]et\((.*)\)", part.strip(), re.S)
        if m:
            e = m[2].strip()
            e = "now" if e == "now.into()" else e.replace("Utc::now().into()", "Utc::now()")
            out.append((m[1], e))
    return out


def insert_sql(table, pairs, fetch, arg, model):
    pairs = [(c, e) for c, e in pairs if e != "None"]
    cols = [c for c, _ in pairs]
    sql = f"INSERT INTO {table} ({', '.join(cols)}) VALUES ({', '.join(f'${n + 1}' for n in range(len(cols)))}) RETURNING *"
    binds = "".join(f"\n        .bind({e})" for _, e in pairs)
    return f"sqlx::query_as::<_, {model}>(\n        {render_sql(sql, 8)},\n    ){binds}\n        .{fetch}({arg})\n        .await?"


def where(table_path, chain):
    """SQL condition and binds from `.filter(X::Column::Y.eq(v))` calls."""
    conds, binds = [], []
    for m in re.finditer(r"\.filter\(\s*(?:[\w:]*)Column::(\w+)\.(eq|is_null)\((.*?)\)\s*,?\s*\)(?=\s*\.|\s*$)", chain, re.S):
        if m[2] == "is_null":
            conds.append(f"{snake(m[1])} IS NULL")
        else:
            binds.append(m[3].strip())
            conds.append(f"{snake(m[1])} = ${len(binds)}")
    return conds, binds


def convert_custom(p):
    s = p.read_text()
    # `use ... patients as patient_entity` aliases hide the table name.
    for module, alias in re.findall(r"\b(\w+) as (\w+_entity)\b", s):
        s = s.replace(f"{module} as {alias}", module)
        s = re.sub(rf"\b{alias}\b", module, s)
    s = re.sub(r"let am = ([\w:]+::ActiveModel \{.*?\});\s*Ok\(am\.insert\(([^)]*)\)\.await\?\.id\)", r"Ok(\1.insert(\2).await?.id)", s, flags=re.S)
    s = re.sub(r"let am = ActiveModel::from_payload\(([^;]*)\);\s*let model = am\.insert\((.*?)\)\.await\?;",
               r"let model = Model::insert_payload(\2, \1).await?;", s, flags=re.S)
    s = re.sub(r"let mut active = ActiveModel::from_payload\(([^;]*)\);(?:\s*active\.\w+ = [^;]*;)+\s*let model = active\.update\((.*?)\)\.await\?;",
               r"let model = Model::update_payload(\2, id, \1).await?;", s, flags=re.S)
    s = re.sub(r"let mut active: ActiveModel = model(?:\.into_active_model\(\))?;\s*active\.deleted_at = [^;]*;\s*active\.update\((.*?)\)\.await\?;",
               r"Model::soft_delete(\1, model.id).await?;", s, flags=re.S)
    s = re.sub(r"\bfind_by_id, ActiveModel, Model\b", "find_by_id, Model", s)
    p.write_text(translate(s, p))


def translate(s, p):
    s = re.sub(r"^\s*use loco_rs::prelude::\*;\n", "", s, flags=re.M) if "tests" in p.parts else s
    s = s.replace("sea_orm::DatabaseConnection", "PgPool")
    s = re.sub(r"\.order_by\(\s*([\w:]+),\s*Order::(Asc|Desc),?\s*\)", lambda m: f".order_by_{m[2].lower()}({m[1]})", s)
    own = re.search(r"(\w+)::\{ActiveModel, Column, Entity, Model\}", s)
    if own:
        s = s.replace(own[0], f"{own[1]}::{{self, Model}}")
        s = re.sub(r"(?<![\w:])(Entity|Column)::", rf"{own[1]}::\1::", s)
    s = re.sub(r"let (\w+) = ([\w:]+::ActiveModel \{(?:[^{}]|\{[^{}]*\})*\});\s*let \1 = \1\.insert\(", r"let \1 = \2.insert(", s)
    s = re.sub(r"use sea_orm::(?:\{[^}]*\}|[^;]*);\n", "", s)
    s = re.sub(r"use crate::models::_entities::\{", "use crate::models::{", s)
    s = re.sub(r"models::_entities::", "models::", s)
    s = s.replace("db: &impl ConnectionTrait", "db: &PgPool")
    s = s.replace("let txn = ctx.db.begin().await?;", "let mut txn = db(&ctx).begin().await?;")
    s = s.replace("let txn = db.begin().await?;", "let mut txn = db.begin().await?;")
    s = s.replace("&DatabaseConnection", "&PgPool")
    s = re.sub(r"Result<(.*), DbErr>", r"sqlx::Result<\1>", s)
    s = s.replace("&ctx.db", "&db(&ctx)")

    # A params struct's literal becomes insert and update methods.
    def params_fn(m):
        ret, table = m[1], m[1].split("::")[-2]
        i, j = block(m.string, m.string.index("ActiveModel {", m.end() - 40))
        pairs = [(c, e) for c, e in set_fields(m.string[i + 1 : j]) if c != "deleted_at" or e != "None"]
        ins = "\n".join(f"        {x}" for x in insert_sql(table, pairs, "fetch_one", "db", ret).splitlines())
        return ins, j
    while True:
        m = re.search(r"fn into_active_model\(self\) -> ((?:\w+::)*\w+::)ActiveModel \{", s)
        if not m:
            break
        path = m[1].rstrip(":")
        table = path.split("::")[-1]
        a, b = block(s, m.end() - 1)
        i, j = block(s, s.index("::ActiveModel {", a))
        pairs = set_fields(s[i + 1 : j])
        lets = s[a + 1 : s.index(table + "::ActiveModel {", a)]
        ins_pairs = [(c, e) for c, e in pairs if not (c == "deleted_at" and e == "None")]
        cols = [c for c, _ in ins_pairs]
        ins = f"INSERT INTO {table} ({', '.join(cols)}) VALUES ({', '.join(f'${n + 1}' for n in range(len(cols)))}) RETURNING *"
        up_pairs = [(c, e) for c, e in pairs if c != "created_at"]
        ups = ", ".join(("deleted_at = NULL" if c == "deleted_at" and e == "None" else f"{c} = ${n + 2}") for n, (c, e) in enumerate(p2 for p2 in up_pairs))
        # Number binds without the literal NULL.
        n = 1
        sets = []
        up_binds = []
        for c, e in up_pairs:
            if c == "deleted_at" and e == "None":
                sets.append("deleted_at = NULL")
            else:
                n += 1
                sets.append(f"{c} = ${n}")
                up_binds.append(e)
        upd = f"UPDATE {table} SET {', '.join(sets)} WHERE id = $1 RETURNING *"
        bi = "".join(f"\n            .bind({e})" for _, e in ins_pairs)
        bu = "".join(f"\n            .bind({e})" for e in up_binds)
        new = (f"async fn insert(self, db: &PgPool) -> sqlx::Result<{path}::Model> {{{lets}"
               f"sqlx::query_as(\n            {render_sql(ins, 12)},\n        ){bi}\n            .fetch_one(db)\n            .await\n    }}\n\n"
               f"    /// Replace the row with this id.\n"
               f"    async fn update(self, db: &PgPool, id: Uuid) -> sqlx::Result<{path}::Model> {{{lets}"
               f"sqlx::query_as(\n            {render_sql(upd, 12)},\n        )\n            .bind(id){bu}\n            .fetch_one(db)\n            .await\n    }}")
        s = s[: m.start()] + new + s[b + 1 :]
    s = s.replace("/// Project the inbound params onto a fresh insert `ActiveModel`.", "/// Insert a row.")
    s = re.sub(r"params\.into_active_model\(\)\.insert\((.*?)\)\.await\?", r"params.insert(\1).await?", s)
    s = re.sub(r"let \w+ = load_\w+\([^;]*;\s*let mut active = params\.into_active_model\(\);\s*active\.id[^;]*;\s*active\.created_at[^;]*;\s*active\.updated_at[^;]*;\s*let model = active\.update\((.*?)\)\.await\?;",
               lambda m: re.match(r"let \w+ = (load_\w+\([^;]*;)", m[0])[1].join(["", "\n    "]) + f"let model = params.update({m[1]}, id).await?;", s, flags=re.S)
    s = re.sub(r"let mut active = params;\s*active\.id[^;]*;\s*active\.created_at[^;]*;\s*active\.updated_at[^;]*;\s*let model = active\.update\((.*?)\)\.await\?;",
               r"let model = params.update(\1, id).await?;", s, flags=re.S)
    s = re.sub(r"let existing = (load_\w+\([^;]*;)", r"\1", s)

    # Literal inserts.
    pos = 0
    while True:
        m = re.compile(r"([\w:]*\w+)::ActiveModel \{").search(s, pos)
        if not m:
            break
        a, b = block(s, m.end() - 1)
        tail = re.match(r"\s*\.insert\((.*?)\)\s*\.await(\??)", s[b + 1 :], re.S)
        if not tail:
            print(f"  LEFT ActiveModel literal in {p}")
            pos = b
            continue
        arg = tail[1].replace("&txn", "&mut *txn")
        table = to_table(m[1])
        sql = insert_sql(table, set_fields(s[a + 1 : b]), "fetch_one", arg, f"{m[1]}::Model")
        s = s[: m.start()] + sql[: -1] + tail[2] + s[b + 1 + tail.end() :]
    s = s.replace("&txn", "&mut *txn")

    # Dashboards.
    s = re.sub(r"let mut query = (\w+)::Entity::find\(\)\s*\.order_by_desc\(\w+::Column::(\w+)\)\s*\.limit\(limit\);\s*"
               r"if let Some\(status\) = params\.status \{\s*query = query\.filter\(\w+::Column::(\w+)\.eq\(status\)\);\s*\}\s*"
               r"let (\w+) = query\.all\((.*?)\)\.await\?;",
               lambda m: (f'let {m[4]}: Vec<{m[1]}::Model> = sqlx::query_as(\n'
                          f'        "SELECT * FROM {m[1]} WHERE ($1::text IS NULL OR {snake(m[3])} = $1) \\\n'
                          f'         ORDER BY {snake(m[2])} DESC LIMIT $2",\n    )\n'
                          f'    .bind(params.status)\n    .bind(i64::try_from(limit).unwrap_or(i64::MAX))\n'
                          f'    .fetch_all({m[5]})\n    .await?;'), s, flags=re.S)
    s = re.sub(r"let rows = (\w+)::Entity::find\(\)\s*\.find_also_related\((\w+)::Entity\)\s*\.order_by_desc\(\w+::Column::(\w+)\)\s*\.limit\(limit\)\s*\.all\((.*?)\)\s*\.await\?;",
               lambda m: (f'let grades: Vec<{m[1]}::Model> =\n'
                          f'        sqlx::query_as("SELECT * FROM {m[1]} ORDER BY {snake(m[3])} DESC LIMIT $1")\n'
                          f'            .bind(i64::try_from(limit).unwrap_or(i64::MAX))\n'
                          f'            .fetch_all({m[4]})\n            .await?;\n'
                          f'    let mut rows = Vec::with_capacity(grades.len());\n'
                          f'    for grade in grades {{\n'
                          f'        let parent = {m[2]}::Model::find_by_id({m[4]}, grade.{m[2].rstrip("s")}_id).await?;\n'
                          f'        rows.push((grade, parent));\n    }}'), s, flags=re.S)

    # Reads.
    s = re.sub(r"([\w:]*\w+)::Entity::find_by_id\(((?:[^()]|\([^()]*\))*)\)\s*\.one\(([^;]*?)\)\s*\.await(\??)",
               lambda m: f"{m[1]}::Model::find_by_id({m[3].rstrip(',').strip()}, {m[2]}).await{m[4]}", s)
    s = re.sub(r"([\w:]*\w+)::Entity::delete_by_id\(([^)]*)\)\s*\.exec\(([^;]*?)\)\s*\.await\?",
               lambda m: f"{m[1]}::Model::delete({m[3].strip()}, {m[2]}).await?", s)

    def query(m):
        path, chain, verb, arg, q = m[1], m[2], m[3], m[4].strip().replace("&txn", "&mut *txn").rstrip(","), m[5]
        table = to_table(path)
        conds, binds = where(path, chain)
        sql = f"SELECT * FROM {table}"
        if conds:
            sql += " WHERE " + " AND ".join(conds)
        orders = [f"{snake(o[2])} {o[1].upper()}" for o in re.finditer(r"\.order_by_(asc|desc)\([\w:]*Column::(\w+)\)", chain)]
        if orders:
            sql += " ORDER BY " + ", ".join(orders)
        lim = re.search(r"\.limit\(([^)]*)\)", chain)
        if lim:
            binds.append(f"i64::try_from({lim[1]}).unwrap_or(i64::MAX)")
            sql += f" LIMIT ${len(binds)}"
        fetch = "fetch_all" if verb == "all" else "fetch_optional"
        b = "".join(f".bind({x})" for x in binds)
        return f'sqlx::query_as::<_, {path}::Model>("{sql}"){b}.{fetch}({arg}).await{q}'
    s = re.sub(r"([\w:]*\w+)::Entity::find\(\)((?:\s*\.(?:filter|order_by_asc|order_by_desc|limit)\((?:[^()]|\([^()]*\))*\))*)\s*\.(one|all)\(([^;]*?)\)\s*\.await(\??)", query, s)

    def count(m):
        path, chain, arg = m[1], m[2], m[3].strip()
        conds, binds = where(path, chain)
        b = "".join(f".bind({x})" for x in binds)
        return (f'sqlx::query_scalar::<_, i64>("SELECT COUNT(*) FROM {to_table(path)} WHERE {" AND ".join(conds)}")'
                f"{b}.fetch_one({arg}).await?")
    s = re.sub(r"([\w:]*\w+)::Entity::find\(\)((?:\s*\.filter\((?:[^()]|\([^()]*\))*\))*)\s*\.count\(([^;]*?)\)\s*\.await\?", count, s)

    def delete(m):
        path, chain, arg = m[1], m[2], m[3].strip().replace("&txn", "&mut *txn")
        conds, binds = where(path, chain)
        b = "".join(f".bind({x})" for x in binds)
        return f'sqlx::query("DELETE FROM {to_table(path)} WHERE {" AND ".join(conds)}"){b}.execute({arg}).await?'
    s = re.sub(r"([\w:]*\w+)::Entity::delete_many\(\)((?:\s*\.filter\((?:[^()]|\([^()]*\))*\))*)\s*\.exec\(([^;]*?)\)\s*\.await\?", delete, s)

    # `let mut x: T::ActiveModel = row.into(); x.f = Set(v); x.update(c)`
    def row_update(m):
        var, path, row, body, arg = m[1], m[2], m[3], m[4], m[5].replace("&txn", "&mut *txn")
        end = m[6]
        pairs = re.findall(rf"{var}\.(\w+) = (?:ActiveValue::)?Set\((.*?)\);", " ".join(body.split()))
        pairs = [(c, "now" if e == "now.into()" else e.replace("Utc::now().into()", "Utc::now()")) for c, e in pairs]
        sets = ", ".join(f"{c} = ${n + 2}" for n, (c, _) in enumerate(pairs))
        bi = "".join(f"\n        .bind({e})" for _, e in pairs)
        return (f'sqlx::query("UPDATE {to_table(path)} SET {sets} WHERE id = $1")\n        .bind({row}.id){bi}\n'
                f"        .execute({arg})\n        .await{end};")
    s = re.sub(r"let mut (\w+): ([\w:]+)::ActiveModel =\s*(\w+)\.into\(\);(.*?)\1\.update\(([^)]*)\)\.await(\?|\.expect\([^)]*\));", row_update, s, flags=re.S)
    return s



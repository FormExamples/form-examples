def entity_struct(s):
    """The Model struct from a SeaORM entity, without SeaORM's attributes."""
    i = s.index("/// Model.") if "/// Model." in s else s.index("#[derive(")
    undocumented = "/// Model." not in s
    _, j = block(s, s.index("pub struct Model", i))
    t = s[i : j + 1]
    t = re.sub(r"[ \t]*#\[sea_orm\((?:[^()\]]|\([^()]*\))*\)\]\n", "", t)
    d = re.search(r"#\[derive\((.*?)\)\]", t)
    names = [x.strip() for x in d[1].split(",") if x.strip() and x.strip() != "DeriveEntityModel"]
    t = t.replace(d[0], f"#[derive({', '.join(names)}, sqlx::FromRow)]", 1)
    if undocumented:
        t = "/// One row.\n#[allow(missing_docs)]\n" + t
    return re.sub(r"\bJson\b", "serde_json::Value", t)



def convert(crate):
    crate = Path(crate)
    t = tomllib.load(open(crate / "Cargo.toml", "rb"))
    pkg = t["package"]["name"]
    lib_path = Path(t["lib"]["path"])
    src_dir = crate / lib_path.parent
    lib = t["lib"].get("name", pkg).replace("-", "_")
    convert_cargo(crate)
    (crate / "Cargo.lock").unlink(missing_ok=True)
    uses_decimal = any(re.search(r"\bDecimal\b", p.read_text()) for p in list((crate / "src").rglob("*.rs")))
    if lib.endswith("_loco_crate"):
        for p in list((crate / "src").rglob("*.rs")) + list((crate / "tests").rglob("*.rs")):
            p.write_text(p.read_text().replace("_loco_crate", "_axum_crate"))
        lib = lib.replace("_loco_crate", "_axum_crate")
    convert_migrations(crate)
    shutil.copytree(HERE / "support", src_dir / "support", dirs_exist_ok=True)
    if uses_decimal:
        c = crate / "Cargo.toml"
        t = c.read_text().replace('"postgres", "runtime-tokio", "tls-rustls-ring-webpki", "uuid"]', '"postgres", "runtime-tokio", "rust_decimal", "tls-rustls-ring-webpki", "uuid"]', 1)
        c.write_text(t.replace("rand = \"0.9\"\n", "rand = \"0.9\"\nrust_decimal = { version = \"1\", features = [\"serde\"] }\n", 1))
        q = src_dir / "support/prelude.rs"
        q.write_text(q.read_text().replace("pub use sqlx::PgPool;\n", "pub use rust_decimal::Decimal;\npub use sqlx::PgPool;\n", 1))
    librs = crate / lib_path
    librs.write_text(librs.read_text().replace("pub mod models;\n", "pub mod models;\npub mod support;\n", 1))
    convert_app(src_dir / "app.rs", pkg)
    main = next(crate.glob("src/**/bin/main.rs"))
    m = main.read_text()
    m = m.replace("use loco_rs::cli;", "use axa::cli::Cli;\nuse clap::Parser;")
    m = m.replace("use migration::Migrator;\n", "")
    m = m.replace("loco_rs::Result", "axa::Result")
    m = m.replace("cli::main::<App, Migrator>().await", "App::run(Cli::parse()).await")
    main.write_text(m)
    convert_models(src_dir)
    for p in (src_dir / "controllers").glob("*.rs"):
        if p.name not in ("mod.rs", "auth.rs", "openapi.rs") and not convert_controller(p):
            print(f"  CUSTOM CONTROLLER {p}")
            convert_custom(p)
    for p in src_dir.rglob("*.rs"):
        if "support" not in p.parts and p.name not in ("app.rs",):
            if re.search(r"::Entity::|ActiveModel", p.read_text()) and "models" not in p.parts and "controllers" not in p.parts:
                print(f"  CUSTOM FILE {p}")
                p.write_text(translate(p.read_text(), p))
            convert_src_file(p)
    for p in (crate / "tests").rglob("*.rs"):
        if re.search(r"::Entity::|ActiveModel", p.read_text()) and p.name != "users.rs":
            print(f"  CUSTOM TEST {p}")
            p.write_text(translate(p.read_text(), p).replace("use crate::support::prelude::*;", f"use {lib}::support::prelude::*;"))
        convert_test_file(p, lib)
    tm = crate / "tests/mod.rs"
    if tm.exists():
        tm.write_text(tm.read_text().rstrip() + "\n" + TEST_HELPERS.replace("@@LIB@@", lib))
    post_fixes(crate, src_dir, pkg)
    shutil.rmtree(crate / "config", ignore_errors=True)
    shutil.rmtree(crate / "examples", ignore_errors=True)
    c = crate / ".cargo/config.toml"
    if c.exists():
        x = re.sub(r'(loco|loco-tool|playground) = "run[^\n]*\n', "", c.read_text())
        x = re.sub(r"\[alias\]\s*(?=\n#|\n\[|\Z)", "", x)
        c.write_text(x.lstrip())


if __name__ == "__main__":
    import traceback
    failed = 0
    for c in sys.argv[1:]:
        print(c)
        try:
            convert(c)
        except Exception:
            failed += 1
            print(f"  FAILED {c}\n" + traceback.format_exc())
    print(f"{failed} failed")

def number(arg):
    """A numeric literal as SeaQuery renders it: `1.0` is `1`."""
    if re.fullmatch(r"-?\d+\.\d+", arg):
        value = float(arg)
        return str(int(value)) if value == int(value) else repr(value)
    return arg


def col_sql(kind):
    m = re.fullmatch(r"(\w+)(?:\((.*)\))?", kind.strip(), re.S)
    name, arg = m[1], (m[2] or "").strip()
    base = {"String": "varchar", "Text": "text", "Integer": "integer", "SmallInteger": "smallint",
            "BigInteger": "bigint", "Double": "double precision", "Float": "real",
            "Boolean": "boolean", "Date": "date", "Time": "time", "Uuid": "uuid",
            "TimestampWithTimeZone": "timestamp with time zone", "Decimal": "decimal",
            "JsonBinary": "jsonb", "Json": "json", "Blob": "bytea"}
    if name == "PkAuto":
        return "bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    if name == "PkUuid":
        return "uuid PRIMARY KEY"
    for suffix, tail in (("WithDefault", "default"), ("Null", "NULL"), ("Uniq", "NOT NULL UNIQUE"), ("", "NOT NULL")):
        stem = name[: -len(suffix)] if suffix and name.endswith(suffix) else (name if not suffix else None)
        if stem in base:
            if tail == "default":
                if arg in ("String::new()", '""'):
                    d = "''"
                else:
                    s = re.fullmatch(r'"(.*)"(?:\.to_string\(\)|\.to_owned\(\)|\.into\(\))?', arg)
                    d = "'" + s[1].replace("'", "''") + "'" if s else number(arg)
                return f"{base[stem]} NOT NULL DEFAULT {d}"
            return f"{base[stem]} {tail}"
    raise ValueError(f"column type {kind}")


def split_top(text):
    """Split a Rust list body on top-level commas."""
    out, depth, cur, in_str = [], 0, "", False
    for i, c in enumerate(text):
        if in_str:
            cur += c
            if c == '"' and text[i - 1] != "\\":
                in_str = False
            continue
        if c == '"':
            in_str = True
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        if c == "," and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += c
    if cur.strip():
        out.append(cur)
    return [x.strip() for x in out if x.strip()]


def strip_comments(s):
    return re.sub(r"^\s*//[^\n]*\n", "", s, flags=re.M)


def balanced(src, start):
    """Text inside the parenthesis that opens at start."""
    depth, j, in_str = 0, start, False
    while True:
        c = src[j]
        if in_str:
            if c == "\\":
                j += 1
            elif c == '"':
                in_str = False
        elif c == '"':
            in_str = True
        elif c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
            if depth == 0:
                return src[start + 1 : j], j + 1
        j += 1


def plural(word):
    """Loco's `normalize_table`, resolved against the tables this crate creates."""
    if word in TABLES:
        return word
    if not TABLES:
        return word
    if word.endswith("is") and word[:-2] + "es" in TABLES:
        return word[:-2] + "es"
    near = sorted(t for t in TABLES if t.startswith(word) and len(t) <= len(word) + 3)
    if near:
        return near[0]
    if word.endswith("s"):
        return word
    if word.endswith("y") and word[-2] not in "aeiou":
        return word[:-1] + "ies"
    return word + "s"


def builder_table_sql(args):
    """`Table::create()` builder form."""
    table = re.search(r'\.table\(Alias::new\("([^"]+)"\)', args)[1]
    lines = []
    pos = 0
    pat = re.compile(r"\.(col|foreign_key)\(")
    while True:
        m = pat.search(args, pos)
        if not m:
            break
        inner, pos = balanced(args, m.end() - 1)
        if m[1] == "col" and inner.startswith("empty_text("):
            lines.append(f'"{re.search(chr(34) + "(.*)" + chr(34), inner)[1]}" varchar NOT NULL DEFAULT \'\'')
        elif m[1] == "col" and inner.startswith("bool_false("):
            lines.append(f'"{re.search(chr(34) + "(.*)" + chr(34), inner)[1]}" boolean NOT NULL DEFAULT false')
        elif m[1] == "col":
            n = re.search(r'ColumnDef::new\(Alias::new\("([^"]+)"\)\)', inner)[1]
            t = {"timestamp_with_time_zone": "timestamp with time zone", "string": "varchar", "text": "text",
                 "boolean": "boolean", "uuid": "uuid", "date": "date", "double": "double precision",
                 "integer": "integer"}
            ty = next(v for k, v in t.items() if f".{k}()" in inner)
            sql = f'"{n}" {ty}'
            sql += " NOT NULL" if ".not_null()" in inner else " NULL"
            d = re.search(r"\.default\(", inner)
            if d:
                dv, _ = balanced(inner, d.end() - 1)
                c = re.fullmatch(r'Expr::cust\("(.*)"\)', dv.strip())
                if c:
                    sql += f" DEFAULT {c[1]}"
                elif "current_timestamp" in dv:
                    sql += " DEFAULT CURRENT_TIMESTAMP"
                elif dv.strip().startswith('"'):
                    sql += " DEFAULT '" + dv.strip().strip('"').replace("'", "''") + "'"
                else:
                    sql += f" DEFAULT {dv.strip()}"
            if ".primary_key()" in inner:
                sql += " PRIMARY KEY"
            if ".unique_key()" in inner:
                sql += " UNIQUE"
            lines.append(sql)
        else:
            name = re.search(r'\.name\("([^"]+)"\)', inner)[1]
            frm = re.search(r'\.from\(\s*Alias::new\("([^"]+)"\),\s*Alias::new\(\s*"([^"]+)",?\s*\),?\s*\)', inner)
            to = re.search(r'\.to\(\s*Alias::new\(\s*"([^"]+)",?\s*\),\s*Alias::new\("([^"]+)"\),?\s*\)', inner)
            act = {"Cascade": "CASCADE", "SetNull": "SET NULL", "Restrict": "RESTRICT", "NoAction": "NO ACTION"}
            ond = re.search(r"on_delete\(ForeignKeyAction::(\w+)\)", inner)
            onu = re.search(r"on_update\(ForeignKeyAction::(\w+)\)", inner)
            lines.append(f'CONSTRAINT "{name}" FOREIGN KEY ("{frm[2]}") REFERENCES "{to[1]}" ("{to[2]}")'
                         + (f" ON DELETE {act[ond[1]]}" if ond else "")
                         + (f" ON UPDATE {act[onu[1]]}" if onu else ""))
    return f'CREATE TABLE IF NOT EXISTS "{table}" (\n    ' + ",\n    ".join(lines) + "\n);"


def create_table_sql(args):
    if "Table::create()" in args:
        return builder_table_sql(args)
    parts = split_top(args)
    table = parts[1].strip('"')
    cols = [split_top(c[1:-1]) for c in split_top(parts[2][2:-1])]
    refs = [[x.strip('"') for x in split_top(r[1:-1])] for r in split_top(parts[3][2:-1])] if len(parts) > 3 else []
    lines = ["created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP",
             "updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP"]
    names = []
    for name, kind in cols:
        n = name.strip('"')
        names.append(n)
        lines.append(f'"{n}" {col_sql(kind.replace("ColType::", ""))}')
    for parent, ref in refs:
        nullable = parent.endswith("?")
        parent = plural(parent.rstrip("?"))
        lines_ref = ref or parent.rstrip("s") + "_id"
        if lines_ref not in names:
            lines.append(f'"{lines_ref}" bigint {"NULL" if nullable else "NOT NULL"}')
        action = "SET NULL ON UPDATE NO ACTION" if nullable else "CASCADE ON UPDATE CASCADE"
        lines.append(f'CONSTRAINT "fk-{table}-{lines_ref}-to-{parent}" FOREIGN KEY ("{lines_ref}") '
                     f'REFERENCES "{parent}" (id) ON DELETE {action}')
    return f'CREATE TABLE IF NOT EXISTS "{table}" (\n    ' + ",\n    ".join(lines) + "\n);"


def builder_col(m):
    name, chain = m[1], m[2]
    t = {"text": "text", "string": "varchar", "boolean": "boolean", "integer": "integer",
         "double": "double precision", "uuid": "uuid", "date": "date",
         "timestamp_with_time_zone": "timestamp with time zone"}
    ty = next(v for k, v in t.items() if f".{k}()" in chain)
    sql = f'"{name}" {ty}'
    if ".not_null()" in chain:
        sql += " NOT NULL"
    d = re.search(r"\.default\((.*?)\)", chain)
    if d:
        v = d[1]
        sql += " DEFAULT " + ("'" + v.strip('"') + "'" if v.startswith('"') else v)
    return sql


def statements(body):
    """Translate one migration direction to SQL statements, in order."""
    body = strip_comments(body)
    out, pos = [], 0
    pat = re.compile(r"\b(create_table|drop_table|add_column|remove_column|create_index|execute_unprepared|alter_table|Table::alter)\(")
    while True:
        m = pat.search(body, pos)
        if not m:
            return out
        kw = m[1]
        args, pos = balanced(body, m.end() - 1)
        if kw == "create_table":
            out.append(create_table_sql(args))
        elif kw == "drop_table":
            t = re.search(r'"([^"]+)"', args)[1]
            out.append(f'DROP TABLE IF EXISTS "{t}" CASCADE;' if False else f'DROP TABLE "{t}";')
        elif kw == "add_column":
            p = split_top(args)
            out.append(f'ALTER TABLE "{p[1].strip(chr(34))}" ADD COLUMN "{p[2].strip(chr(34))}" {col_sql(p[3].replace("ColType::", ""))};')
        elif kw == "remove_column":
            p = split_top(args)
            out.append(f'ALTER TABLE "{p[1].strip(chr(34))}" DROP COLUMN "{p[2].strip(chr(34))}";')
        elif kw == "create_index":
            n = re.search(r'\.name\("([^"]+)"\)', args)[1]
            t = re.search(r'\.table\(Alias::new\("([^"]+)"\)', args)[1]
            cs = re.findall(r'\.col\(Alias::new\("([^"]+)"\)', args)
            u = "UNIQUE " if ".unique()" in args else ""
            ine = "IF NOT EXISTS " if ".if_not_exists()" in args else ""
            out.append(f'CREATE {u}INDEX {ine}"{n}" ON "{t}" (' + ", ".join(f'"{c}"' for c in cs) + ");")
        elif kw == "execute_unprepared":
            out.append(re.search(r'"(.*)"', args, re.S)[1].rstrip(";") + ";")
        elif kw == "Table::alter":
            end = body.find("alter_table", pos)
            seg = body[pos:end]
            t = re.search(r'\.table\(Alias::new\("([^"]+)"\)', seg)[1]
            for c in re.finditer(r'\.add_column\(ColumnDef::new\(Alias::new\("([^"]+)"\)\)(.*?)\.to_owned\(\)\)', seg, re.S):
                out.append(f'ALTER TABLE "{t}" ADD COLUMN {builder_col(c)};')
            for c in re.finditer(r'\.drop_column\(Alias::new\("([^"]+)"\)\)', seg):
                out.append(f'ALTER TABLE "{t}" DROP COLUMN "{c[1]}";')
            pos = body.index(")", end) + 1


def convert_migrations(crate):
    if (crate / "migrations").exists():
        return
    src = crate / "migration/src"
    order = re.findall(r"Box::new\((m\w+)::Migration\)", (src / "lib.rs").read_text())
    dest = crate / "migrations"
    dest.mkdir(exist_ok=True)
    version = 0
    TABLES.clear()
    for name in order:
        TABLES.update(re.findall(r'create_table\(\s*m,\s*"(\w+)"', (src / f"{name}.rs").read_text()))
        TABLES.update(re.findall(r'Table::create\(\)\s*\.table\(Alias::new\("(\w+)"\)', (src / f"{name}.rs").read_text()))
    for name in order:
        s = (src / f"{name}.rs").read_text()
        m = re.fullmatch(r"m(\d{8})_?(\d{6})_(\w+)", name)
        up = fn_body(s, r"fn up\(")
        down = fn_body(s, r"fn down\(")
        # sqlx applies migrations in version order, and this crate's list order
        # is the truth, so a stamp that sorts too early moves up.
        version = max(version + 1, int(m[1] + m[2]))
        stem = f"{version}_{m[3]}"
        (dest / f"{stem}.up.sql").write_text("\n\n".join(statements(up)) + "\n")
        (dest / f"{stem}.down.sql").write_text("\n\n".join(statements(down)) + "\n")
    shutil.rmtree(crate / "migration")



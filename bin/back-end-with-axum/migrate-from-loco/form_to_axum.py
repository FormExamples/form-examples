def convert_app(path, pkg):
    src = path.read_text()
    use = re.search(r"#\[allow\(unused_imports\)\]\nuse crate::\{(.*?)\};", src, re.S)
    parts = []
    for item in split_top(" ".join(use[1].split())) if use else []:
        item = item.strip()
        if item in ("controllers", "tasks") or item.startswith("models::_entities"):
            continue
        parts.append(item)
    parts = ", ".join(parts)
    workers = fn_body(src, r"async fn connect_workers\(")
    workers = re.sub(r"(queue\.register\(.*?\))\.await\?;", r"\1;", workers, flags=re.S)
    tasks = fn_body(src, r"fn register_tasks\(")
    routes = fn_body(src, r"fn routes\(")
    trunc = ", ".join(f'"{t}"'
                    for t in re.findall(r"truncate_table\(&ctx\.db, (?:\w+::)*?(\w+)::Entity\)", fn_body(src, r"async fn truncate\(")))
    body = fn_body(src, r"async fn seed\(")
    seeds = re.findall(r"seed::<(?:[\w]+::)*?(\w+)::ActiveModel>\(\s*&ctx\.db,\s*(&format!\(.*?\)|\"[^\"]*\"|&[^,]+),?\s*\)\s*\.await\?;", body, re.S)
    seed = "".join(f'        support::seed(&pool, "{t}", {" ".join(q.split())}).await?;\n' for t, q in seeds)
    if body.count("seed::<") != len(seeds):
        print(f"  CUSTOM SEED {path}")
    out = (HERE / "app.rs.tmpl").read_text()
    if not trunc:
        out = out.replace("        truncate(&db(ctx), &[@@TRUNCATE@@]).await?;\n", "        let _ = ctx;\n")
    for k, v in [("USE", parts), ("DB", pkg), ("ROUTES", routes), ("WORKERS", workers),
                 ("TASKS", tasks.rstrip() + "\n    "), ("TRUNCATE", trunc), ("SEED", seed)]:
        out = out.replace(f"@@{k}@@", v)
    path.write_text(out)


